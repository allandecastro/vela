using System.Linq;
using Microsoft.Xrm.Sdk.Metadata;
using Vela.Cli;
using Vela.Cli.Tests.TestSupport;
using Xunit;

namespace Vela.Cli.Tests;

/// <summary>
/// Golden tests for <see cref="TableTypeTsGenerator"/>: table metadata must emit the vela-client Web API record
/// contract shape (see <c>vela-client/src/webapi/record.ts</c> and <c>test/fixtures/tables/*.ts</c>). The emitter
/// is deterministic - columns follow metadata order with the primary key first, and option sets follow
/// first-reference order into the shared <c>option-sets.ts</c>.
/// </summary>
public class TableTypeTsGeneratorTests
{
    private static EntityMetadata Account() =>
        MetadataFactory.Entity("account", "Account")
            .PrimaryId("accountid", "AccountId").Display("Account")
            .String("name", "Name", maxLength: 160).Display("Account Name")
            .String("telephone1", "Telephone1").Display("Main Phone")
            .Money("revenue", "Revenue").Display("Annual Revenue")
            .Integer("numberofemployees", "NumberOfEmployees").Display("Employees")
            .DateTime("createdon", "CreatedOn").Display("Created On")
            .Boolean("donotemail", "DoNotEmail").Display("Do Not Email")
            .Choice("industrycode", "IndustryCode", global: false, null, (1, "Accounting"), (2, "Consulting"), (3, "Manufacturing"), (4, "Retail"), (5, "Technology")).Display("Industry")
            .Choice("statuscode", "StatusCode", global: false, null, (1, "Active"), (2, "Inactive")).Display("Status Reason")
            .MultiSelect("new_servicetypes", "new_ServiceTypes", global: false, null, (1, "Consulting"), (2, "Support"), (3, "Training"), (4, "Managed")).Display("Service Types")
            .Lookup("primarycontactid", "PrimaryContactId", "contact").Display("Primary Contact")
            .Build();

    private static EntityMetadata Contact() =>
        MetadataFactory.Entity("contact", "Contact")
            .PrimaryId("contactid", "ContactId").Display("Contact")
            .String("firstname", "FirstName").Display("First Name")
            .String("lastname", "LastName").Display("Last Name")
            .String("fullname", "FullName").Display("Full Name")
            .String("emailaddress1", "EMailAddress1").Display("Email")
            .DateTime("birthdate", "BirthDate").Display("Birthday")
            .Money("creditlimit", "CreditLimit").Display("Credit Limit")
            .Boolean("donotemail", "DoNotEmail").Display("Do Not Email")
            .Choice("gendercode", "GenderCode", global: false, null, (1, "Male"), (2, "Female")).Display("Gender")
            .Choice("statuscode", "StatusCode", global: false, null, (1, "Active"), (2, "Inactive")).Display("Status")
            .Customer("parentcustomerid", "ParentCustomerId", "account", "contact").Display("Company Name")
            .Build();

    private static string Generate(EntityMetadata entity, string fileName) =>
        TableTypeTsGenerator.Generate(new[] { entity }).Single(m => m.FileName == fileName).Code;

    [Fact]
    public void Account_Table_Matches_Golden()
    {
        const string expected = """
            // Generated by "vela models --tables --lang ts" - do not edit by hand.
            import type { DataverseRecordMeta } from 'vela-client/webapi';
            import type {
              account_industrycode,
              account_statuscode,
              account_new_servicetypes,
            } from '../option-sets';

            export interface Account extends DataverseRecordMeta {
              accountid: string;
              name?: string | null;
              telephone1?: string | null;
              revenue?: number | null;
              numberofemployees?: number | null;
              createdon?: string | null;
              donotemail?: boolean | null;
              industrycode?: account_industrycode | null;
              statuscode?: account_statuscode | null;
              new_servicetypes?: account_new_servicetypes[] | null;
              _primarycontactid_value?: string | null;
            }

            """;

        Assert.Equal(expected.ReplaceLineEndings("\n"), Generate(Account(), "tables/account.ts"));
    }

    [Fact]
    public void Contact_Table_Matches_Golden()
    {
        // Two enums fit within Prettier's 80-column print width, so the enum import stays on one line.
        const string expected = """
            // Generated by "vela models --tables --lang ts" - do not edit by hand.
            import type { DataverseRecordMeta } from 'vela-client/webapi';
            import type { contact_gendercode, contact_statuscode } from '../option-sets';

            export interface Contact extends DataverseRecordMeta {
              contactid: string;
              firstname?: string | null;
              lastname?: string | null;
              fullname?: string | null;
              emailaddress1?: string | null;
              birthdate?: string | null;
              creditlimit?: number | null;
              donotemail?: boolean | null;
              gendercode?: contact_gendercode | null;
              statuscode?: contact_statuscode | null;
              _parentcustomerid_value?: string | null;
            }

            """;

        Assert.Equal(expected.ReplaceLineEndings("\n"), Generate(Contact(), "tables/contact.ts"));
    }

    [Fact]
    public void Option_Sets_File_Is_The_Shared_Forms_Artifact()
    {
        // The shared option-sets.ts carries the --forms banner and merges both tables' enums in reference order.
        const string expected = """
            // Generated by "vela models --forms --lang ts" - do not edit by hand.

            export enum contact_gendercode {
              Male = 1,
              Female = 2,
            }

            export enum contact_statuscode {
              Active = 1,
              Inactive = 2,
            }

            export enum account_industrycode {
              Accounting = 1,
              Consulting = 2,
              Manufacturing = 3,
              Retail = 4,
              Technology = 5,
            }

            export enum account_statuscode {
              Active = 1,
              Inactive = 2,
            }

            export enum account_new_servicetypes {
              Consulting = 1,
              Support = 2,
              Training = 3,
              Managed = 4,
            }

            """;

        string optionSets = TableTypeTsGenerator.Generate(new[] { Contact(), Account() })
            .Single(m => m.FileName == "option-sets.ts").Code;

        Assert.Equal(expected.ReplaceLineEndings("\n"), optionSets);
    }

    [Fact]
    public void Generates_One_Table_File_Per_Entity_Plus_Shared_Option_Sets()
    {
        string[] files = TableTypeTsGenerator.Generate(new[] { Account(), Contact() })
            .Select(m => m.FileName)
            .ToArray();

        Assert.Equal(
            new[] { "tables/account.ts", "tables/contact.ts", "option-sets.ts" },
            files);
    }

    [Fact]
    public void Primary_Key_Is_Required_And_Non_Nullable()
    {
        string ts = Generate(Account(), "tables/account.ts");

        Assert.Contains("  accountid: string;\n", ts);
        Assert.DoesNotContain("accountid?:", ts);
    }

    [Fact]
    public void Lookup_Emits_Only_The_Value_Key()
    {
        string ts = Generate(Account(), "tables/account.ts");

        Assert.Contains("_primarycontactid_value?: string | null;", ts);
        // No navigation property / bind key in the record shape.
        Assert.DoesNotContain("primarycontactid?:", ts);
        Assert.DoesNotContain("@odata.bind", ts);
    }

    [Fact]
    public void Generate_Null_Throws()
    {
        Assert.Throws<System.ArgumentNullException>(() => TableTypeTsGenerator.Generate(null!));
    }

    [Fact]
    public void Table_Without_Choices_Emits_No_Option_Set_Import_Or_File()
    {
        EntityMetadata entity = MetadataFactory.Entity("task", "Task")
            .PrimaryId("activityid", "ActivityId")
            .String("subject", "Subject").Display("Subject")
            .Build();

        var files = TableTypeTsGenerator.Generate(new[] { entity });

        string ts = files.Single(m => m.FileName == "tables/task.ts").Code;
        Assert.DoesNotContain("option-sets", ts);
        Assert.DoesNotContain(files, f => f.FileName == "option-sets.ts");
    }

    [Fact]
    public void File_And_Image_Columns_Map_To_String()
    {
        EntityMetadata entity = MetadataFactory.Entity("account", "Account")
            .PrimaryId("accountid", "AccountId")
            .File("new_contractfile", "new_ContractFile").Display("Contract")
            .Image("entityimage", "EntityImage").Display("Logo")
            .Build();

        string ts = Generate(entity, "tables/account.ts");

        Assert.Contains("new_contractfile?: string | null;", ts);
        Assert.Contains("entityimage?: string | null;", ts);
    }

    [Fact]
    public void Multi_Select_Choice_Is_An_Enum_Array()
    {
        string ts = Generate(Account(), "tables/account.ts");

        Assert.Contains("new_servicetypes?: account_new_servicetypes[] | null;", ts);
    }

    [Fact]
    public void PartyList_Column_Is_Omitted()
    {
        EntityMetadata entity = MetadataFactory.Entity("email", "Email")
            .PrimaryId("activityid", "ActivityId")
            .String("subject", "Subject").Display("Subject")
            .PartyList("to", "To", "systemuser", "contact").Display("To")
            .Build();

        string ts = Generate(entity, "tables/email.ts");

        Assert.Contains("subject?: string | null;", ts);
        Assert.DoesNotContain("to", ts.Substring(ts.IndexOf("interface", System.StringComparison.Ordinal)));
    }

    [Fact]
    public void Global_Option_Set_Uses_Its_Own_Shared_Name()
    {
        EntityMetadata entity = MetadataFactory.Entity("account", "Account")
            .PrimaryId("accountid", "AccountId")
            .Choice("preferredcolor", "PreferredColor", global: true, "vela_color", (1, "Red"), (2, "Green")).Display("Color")
            .Build();

        var files = TableTypeTsGenerator.Generate(new[] { entity });
        string table = files.Single(m => m.FileName == "tables/account.ts").Code;
        string optionSets = files.Single(m => m.FileName == "option-sets.ts").Code;

        Assert.Contains("import type { vela_color } from '../option-sets';", table);
        Assert.Contains("preferredcolor?: vela_color | null;", table);
        Assert.Contains("export enum vela_color {", optionSets);
    }
}
