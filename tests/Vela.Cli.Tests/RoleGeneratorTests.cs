using System;
using System.Collections.Generic;
using Vela.Cli;
using Xunit;

namespace Vela.Cli.Tests;

public class RoleGeneratorTests
{
    private static readonly Guid SalesId = new Guid("11111111-1111-1111-1111-111111111111");

    // The generated grant field type, repeated across the shape assertions below.
    private const string GrantsType = "(string Entity, string Level, string Privilege)[]";

    private static RoleModel Salesperson(params RoleGrantModel[] grants) =>
        new RoleModel("Salesperson", SalesId, grants);

    private static string Generate(params RoleModel[] roles) =>
        RoleGenerator.Generate(roles, new RoleGenOptions("Acme.Tests.Roles")).Code;

    [Fact]
    public void Emits_a_dependency_light_roles_class_in_the_namespace()
    {
        string code = Generate(Salesperson(new RoleGrantModel("account", "Read", "BusinessUnit")));

        Assert.StartsWith("// <auto-generated/>", code);
        Assert.Contains("namespace Acme.Tests.Roles", code);
        Assert.Contains("using System;", code);
        Assert.DoesNotContain("using Vela.Testing.Security;", code); // dependency-light: no test-only types
        Assert.Contains("public static class Roles", code);
        Assert.Equal("Roles.cs", RoleGenerator.Generate(new[] { Salesperson() }, new RoleGenOptions("N")).FileName);
    }

    [Fact]
    public void Emits_name_constant_root_id_and_grant_data_per_role()
    {
        string code = Generate(Salesperson(new RoleGrantModel("account", "Read", "Organization")));

        Assert.Contains("public const string SalespersonName = \"Salesperson\";", code);
        Assert.Contains($"public static readonly Guid SalespersonId = new Guid(\"{SalesId:D}\");", code);
        Assert.Contains($"public static readonly {GrantsType} Salesperson = new[]", code);
        Assert.Contains("(\"account\", \"Organization\", \"Read\"),", code);
    }

    [Fact]
    public void Grants_are_ordered_by_entity_then_privilege()
    {
        string code = Generate(Salesperson(
            new RoleGrantModel("contact", "Read", "Organization"),
            new RoleGrantModel("account", "Write", "BusinessUnit"),
            new RoleGrantModel("account", "Create", "User")));

        int account = code.IndexOf("(\"account\", \"User\", \"Create\")", StringComparison.Ordinal);
        int accountWrite = code.IndexOf("(\"account\", \"BusinessUnit\", \"Write\")", StringComparison.Ordinal);
        int contact = code.IndexOf("(\"contact\", \"Organization\", \"Read\")", StringComparison.Ordinal);

        Assert.True(account < accountWrite, "account grants ordered by privilege");
        Assert.True(accountWrite < contact, "account grants precede contact grants");
    }

    [Fact]
    public void A_role_with_no_grants_emits_an_empty_grant_array()
    {
        string code = Generate(Salesperson());

        Assert.Contains($"public static readonly {GrantsType} Salesperson =", code);
        Assert.Contains("new (string Entity, string Level, string Privilege)[0];", code);
        Assert.DoesNotContain(" = new[]", code); // no populated initializer
    }

    [Theory]
    [InlineData("Sales Manager", "SalesManager")]
    [InlineData("System Administrator", "SystemAdministrator")]
    [InlineData("CSR - Level 2", "CSRLevel2")]
    [InlineData("2nd line", "Role2ndLine")]        // can't start with a digit
    [InlineData("class", "Class")]                 // PascalCasing upper-cases the first letter, so never a keyword
    public void Role_names_become_valid_csharp_identifiers(string roleName, string expectedIdentifier)
    {
        string code = RoleGenerator.Generate(
            new[] { new RoleModel(roleName, SalesId, Array.Empty<RoleGrantModel>()) },
            new RoleGenOptions("N")).Code;

        Assert.Contains($"public static readonly {GrantsType} {expectedIdentifier} =", code);
        Assert.Contains($"public const string {expectedIdentifier}Name = \"{roleName}\";", code);
    }

    [Fact]
    public void Names_that_collide_after_sanitizing_get_unique_identifiers()
    {
        string code = RoleGenerator.Generate(
            new[]
            {
                new RoleModel("Sales Rep", Guid.NewGuid(), Array.Empty<RoleGrantModel>()),
                new RoleModel("Sales-Rep", Guid.NewGuid(), Array.Empty<RoleGrantModel>()),
            },
            new RoleGenOptions("N")).Code;

        Assert.Contains($"public static readonly {GrantsType} SalesRep =", code);
        Assert.Contains($"public static readonly {GrantsType} SalesRep_2 =", code);
    }

    [Fact]
    public void Roles_are_emitted_in_a_stable_order()
    {
        string code = RoleGenerator.Generate(
            new[]
            {
                new RoleModel("Zeta", Guid.NewGuid(), Array.Empty<RoleGrantModel>()),
                new RoleModel("Alpha", Guid.NewGuid(), Array.Empty<RoleGrantModel>()),
            },
            new RoleGenOptions("N")).Code;

        Assert.True(code.IndexOf("AlphaName", StringComparison.Ordinal) < code.IndexOf("ZetaName", StringComparison.Ordinal));
    }

    [Fact]
    public void A_role_name_with_special_characters_is_escaped()
    {
        string code = RoleGenerator.Generate(
            new[] { new RoleModel("A&B \"role\"", SalesId, Array.Empty<RoleGrantModel>()) },
            new RoleGenOptions("N")).Code;

        Assert.Contains("= \"A&B \\\"role\\\"\";", code); // the string constant is a valid, escaped C# literal
        Assert.Contains("A&amp;B", code);                 // the XML doc comment escapes the ampersand
    }

    [Fact]
    public void Guards_null_roles_and_missing_namespace()
    {
        Assert.Throws<ArgumentNullException>(() => RoleGenerator.Generate(null!, new RoleGenOptions("N")));
        Assert.Throws<ArgumentException>(() => RoleGenerator.Generate(Array.Empty<RoleModel>(), new RoleGenOptions("  ")));
    }

    [Fact]
    public void Null_or_blank_roles_and_grants_are_skipped_not_thrown()
    {
        string code = RoleGenerator.Generate(
            new[]
            {
                null!,                                                    // null role -> skipped
                new RoleModel(" ", SalesId, Array.Empty<RoleGrantModel>()), // blank name -> skipped
                new RoleModel("Ok", SalesId, new[] { null!, new RoleGrantModel(" ", "Read", "User") }), // null/blank grant -> skipped
            },
            new RoleGenOptions("N")).Code;

        Assert.Contains($"public static readonly {GrantsType} Ok =", code);
        Assert.Contains("new (string Entity, string Level, string Privilege)[0];", code); // the only grant had a blank entity
    }

    [Fact]
    public void Generates_the_exact_expected_source()
    {
        string code = RoleGenerator.Generate(
            new[] { new RoleModel("Salesperson", SalesId, new[] { new RoleGrantModel("account", "Read", "BusinessUnit") }) },
            new RoleGenOptions("Acme.Tests.Roles")).Code;

        // Full snapshot (line endings normalized so it holds on both Windows CI and dev machines). Any change to an
        // emitted string breaks this, which is exactly what pins the generator's output.
        string expected = string.Join("\n", new[]
        {
            "// <auto-generated/>",
            "namespace Acme.Tests.Roles",
            "{",
            "    using System;",
            "",
            "    /// <summary>",
            "    /// Security roles generated from the environment (name, real root id, and real privilege grants as",
            "    /// [entity, access level, privilege] name triples). Dependency-light (no test-only types), so it lives",
            "    /// with the shared models and both runtime plugin code and tests can use it. Configure the harness via",
            "    /// <c>WithSecurity(s =&gt; s.Role(Roles.XName, Roles.XId, Roles.X).User(userId, buId, Roles.XName))</c>",
            "    /// — <c>Roles.XId</c> is the root role id: systemuserroles/teamroles hold the copy of the principal's business",
            "    /// unit, so plugin logic matches role membership on role.parentrootroleid == Roles.XId.",
            "    /// </summary>",
            "    public static class Roles",
            "    {",
            "        /// <summary>The \"Salesperson\" security role.</summary>",
            "        public const string SalespersonName = \"Salesperson\";",
            "",
            "        /// <summary>The root id of the \"Salesperson\" security role.</summary>",
            "        public static readonly Guid SalespersonId = new Guid(\"11111111-1111-1111-1111-111111111111\");",
            "",
            "        /// <summary>The privilege grants of the \"Salesperson\" role ([entity, access level, privilege]).</summary>",
            "        public static readonly (string Entity, string Level, string Privilege)[] Salesperson = new[]",
            "        {",
            "            (\"account\", \"BusinessUnit\", \"Read\"),",
            "        };",
            "    }",
            "}",
            "",
        });

        Assert.Equal(expected, code.Replace("\r\n", "\n"));
    }
}
