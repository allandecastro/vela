    [Fact]
    public void Distinct_shapes_under_one_name_keep_the_plain_name_for_the_first_in_signature_order_and_hash_the_others()
    {
        GeneratorHarness.Run run = GeneratorHarness.Execute(@"
namespace Demo
{
    using Vela.Plugin;
    public sealed partial class Collide : EntityPluginBase<Account>
    {
        protected override void RegisterPluginSteps()
        {
            RegisterStep().OnUpdate().PostOperation().Sync().WithPostImage(a => a.Telephone1).Handle(() => { });
            RegisterStep().OnUpdate().PostOperation().Sync().WithPostImage(a => a.Name).Handle(() => { });
            RegisterStep().OnUpdate().PostOperation().Sync().WithPostImage(a => a.Name).Handle(() => { });
        }
    }
}
");

        Assert.Empty(run.CompileErrors);
        // The identical Name shape is emitted once; ordered by column signature ("Name:..." < "Telephone1:..."), the
        // Name shape keeps the plain name whatever the source order, and the Telephone1 shape gets the FNV-1a hash of
        // its signature, so the name is stable across builds.
        string hash = Fnv1a("Telephone1:string?:telephone1");
        AssertGeneratedFiles(run,
            "Demo_Collide_UpdatePostOp_PostImage.g.cs",
            $"Demo_Collide_UpdatePostOp_PostImage_{hash}.g.cs");
        Assert.Equal("b1dd0e87", hash);
