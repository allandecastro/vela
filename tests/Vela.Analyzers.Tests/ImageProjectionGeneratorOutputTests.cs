using System.Collections.Generic;
using System.Linq;
using Microsoft.CodeAnalysis;
using Xunit;

namespace Vela.Analyzers.Tests;

// Pins the exact source the ImageProjectionGenerator emits (projection and context, file hint names, layout and
// documentation), the type names it derives for every trigger path, how it maps a selector to a column, and when it
// stays silent. The other generator tests check fragments; these compare whole files, so a dropped line, a wrong
// indent or a swapped Pre/Post word fails here.
public sealed class ImageProjectionGeneratorOutputTests
{
    private static string Normalize(string text) => text.Replace("\r\n", "\n");

    private static string Source(GeneratorHarness.Run run, string hintName)
    {
        Assert.True(run.Sources.ContainsKey(hintName), $"'{hintName}' not generated. Generated: {string.Join(", ", run.Sources.Keys)}");
        return Normalize(run.Sources[hintName]);
    }

    private static void AssertGeneratedFiles(GeneratorHarness.Run run, params string[] hintNames)
        => Assert.Equal(hintNames.OrderBy(n => n, System.StringComparer.Ordinal), run.Sources.Keys.OrderBy(n => n, System.StringComparer.Ordinal));

    [Fact]
    public void Update_step_with_an_aliased_pre_image_and_a_post_image_emits_the_exact_projections_and_context()
    {
        GeneratorHarness.Run run = GeneratorHarness.Execute(@"
namespace Demo
{
    using Vela.Plugin;
    public sealed partial class AccountAudit : EntityPluginBase<Account>
    {
        protected override void RegisterPluginSteps()
            => RegisterStep().OnUpdate().PostOperation().Sync()
                .WithPreImage(""Before"", a => a.Name)
                .WithPostImage(a => a.Revenue, a => a.NumberOfEmployees)
                .Handle(OnUpdated);
        private void OnUpdated() { }
    }
}
");

        Assert.Empty(run.GeneratorDiagnostics);
        Assert.Empty(run.CompileErrors);
        AssertGeneratedFiles(run,
            "Demo_AccountAudit_OnUpdated_PostImage.g.cs",
            "Demo_AccountAudit_OnUpdated_PreImage_Before.g.cs",
            "Demo_AccountAudit_OnUpdatedContext.Context.g.cs");

        Assert.Equal("""
            // <auto-generated/> Vela typed image projection. Do not edit.
            #nullable enable

            namespace Demo
            {
                partial class AccountAudit
                {
                    /// <summary>
                    /// Generated projection: exposes only the columns this step captured in WithPreImage/WithPostImage(...).
                    /// A column the step did not capture is absent here (reading it is a compile error, not a silent null);
                    /// add it to the capture to read it. Read this via ctx.PreImageAs&lt;T&gt;() / ctx.PostImageAs&lt;T&gt;().
                    /// </summary>
                    public sealed class OnUpdated_PostImage : global::Vela.Context.IImageProjection
                    {
                        [global::Microsoft.Xrm.Sdk.AttributeLogicalName("revenue")]
                        public decimal? Revenue { get; set; }
                        [global::Microsoft.Xrm.Sdk.AttributeLogicalName("numberofemployees")]
                        public int? NumberOfEmployees { get; set; }

                        global::Microsoft.Xrm.Sdk.Entity? global::Vela.Context.IImageProjection.Source { get; set; }

                        /// <summary>
                        /// Widens this captured-columns projection to the full early-bound image (Id, logical name and every
                        /// attribute the image carried). Explicit on purpose: prefer reading the projection directly; cast only
                        /// when a service needs the whole entity. Equivalent to ctx.GetPostImage&lt;global::Demo.Account&gt;()
                        /// (both go through Entity.ToEntity, so the Id is preserved); returns null for an absent image.
                        /// </summary>
                        public static explicit operator global::Demo.Account(OnUpdated_PostImage? projection)
                            => projection is global::Vela.Context.IImageProjection { Source: { } source } ? source.ToEntity<global::Demo.Account>() : null!;
                    }
                }
            }

            """, Source(run, "Demo_AccountAudit_OnUpdated_PostImage.g.cs"));

        string pre = Source(run, "Demo_AccountAudit_OnUpdated_PreImage_Before.g.cs");
        Assert.Contains("""
                    public sealed class OnUpdated_PreImage_Before : global::Vela.Context.IImageProjection
                    {
                        [global::Microsoft.Xrm.Sdk.AttributeLogicalName("name")]
                        public string? Name { get; set; }

            """, pre);
        Assert.Contains("Equivalent to ctx.GetPreImage&lt;global::Demo.Account&gt;(\"Before\")", pre);
        Assert.DoesNotContain("GetPostImage", pre);

        Assert.Equal("""
            // <auto-generated/> Vela typed step context. Do not edit.
            #nullable enable

            namespace Demo
            {
                partial class AccountAudit
                {
                    /// <summary>
                    /// Generated step context for the 'OnUpdated' handler: the message context plus the typed image(s) this step captured.
                    /// Bind it with .Handle(OnUpdated). Capturing an image later adds a typed ctx.PreImage / ctx.PostImage without changing this signature.
                    /// </summary>
                    public sealed class OnUpdatedContext : global::Vela.Context.UpdatePostContext<global::Demo.Account>
                    {
                        public OnUpdatedContext(global::Vela.Context.ILocalPluginContext inner) : base(inner) { }
                        public new OnUpdated_PreImage_Before? PreImage => global::Vela.Context.ImageProjectionExtensions.PreImageAs<OnUpdated_PreImage_Before>(this, "Before");
                        public new OnUpdated_PostImage? PostImage => global::Vela.Context.ImageProjectionExtensions.PostImageAs<OnUpdated_PostImage>(this);
                    }
                }
            }

            """, Source(run, "Demo_AccountAudit_OnUpdatedContext.Context.g.cs"));
    }

