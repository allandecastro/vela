// Analyzers never report in generated code: a source generator or a designer file is not the developer's to fix.
// Each case is a violation an existing test of that analyzer flags (built with that test class's own harness), run
// twice: as hand-written code it must be reported, and the same code behind an <auto-generated/> header must not.
public sealed class GeneratedCodeTests
{
    private static string Compose(Type testClass, string helper, string snippet)
    {
        MethodInfo method = testClass.GetMethod(helper, BindingFlags.NonPublic | BindingFlags.Static)
            ?? throw new MissingMethodException(testClass.Name, helper);
        return (string)method.Invoke(null, new object[] { snippet })!;
    }

    private static string Harness(Type testClass)
        => (string)(testClass.GetField("Harness", BindingFlags.NonPublic | BindingFlags.Static)
            ?? throw new MissingFieldException(testClass.Name, "Harness")).GetRawConstantValue()!;

    private const string PluginShell = @"
namespace Demo
{
    using System;
    using System.IO;
    using Microsoft.Xrm.Sdk;
    public class MyPlugin : IPlugin
    {
        BODY
    }
}";

    public static IEnumerable<object[]> Cases()
    {
        yield return Case<AsyncTargetWriteAnalyzer>(Compose(typeof(AsyncTargetWriteAnalyzerTests), "InClass",
            "public void Reg() { RegisterStep().OnUpdate().PostOperation().Async().Handle(OnUpd); }\n" +
