            "        private void OnUpd(ILocalPluginContext ctx) { object? x = ctx.PreImage; }"));
    }

    private static object[] Case<TAnalyzer>(string source) where TAnalyzer : DiagnosticAnalyzer, new()
        => new object[] { typeof(TAnalyzer).Name, source };

    private static async Task<ImmutableArray<Diagnostic>> Analyze(string analyzerName, string source)
    {
        DiagnosticAnalyzer analyzer = (DiagnosticAnalyzer)Activator.CreateInstance(
            typeof(ImageProjectionGenerator).Assembly.GetTypes().Single(t => t.Name == analyzerName))!;
        IEnumerable<MetadataReference> references = ((string)AppContext.GetData("TRUSTED_PLATFORM_ASSEMBLIES")!)
            .Split(Path.PathSeparator)
            .Where(p => p.Length > 0)
            .Select(p => (MetadataReference)MetadataReference.CreateFromFile(p));
        CSharpCompilation compilation = CSharpCompilation.Create(
            "generated_code_test",
            new[] { CSharpSyntaxTree.ParseText(source, new CSharpParseOptions(LanguageVersion.Latest), path: "Plugin.cs") },
            references,
            new CSharpCompilationOptions(OutputKind.DynamicallyLinkedLibrary, nullableContextOptions: NullableContextOptions.Enable));
        string id = analyzer.SupportedDiagnostics[0].Id;
        ImmutableArray<Diagnostic> diagnostics = await compilation.WithAnalyzers(ImmutableArray.Create(analyzer)).GetAnalyzerDiagnosticsAsync();
        return diagnostics.Where(d => d.Id == id).ToImmutableArray();
    }

    [Theory]
    [MemberData(nameof(Cases))]
    public async Task A_violation_is_reported_in_hand_written_code_but_not_in_generated_code(string analyzerName, string source)
    {
        Assert.NotEmpty(await Analyze(analyzerName, source));
        Assert.Empty(await Analyze(analyzerName, "// <auto-generated/>\n" + source));
    }
}
