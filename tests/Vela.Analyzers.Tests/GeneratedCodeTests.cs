        yield return Case<ColumnSelectorAnalyzer>(Compose(typeof(ColumnSelectorAnalyzerTests), "InMethod", "Steps.Filtering<Account>(x => x.LogicalName);"));
        yield return Case<DuplicateColumnAnalyzer>(Compose(typeof(DuplicateColumnAnalyzerTests), "InMethod", "RegisterStep().FilterOn(a => a.Name, a => a.Name).Handle();"));
        yield return Case<DuplicateModifierAnalyzer>(Compose(typeof(DuplicateModifierAnalyzerTests), "InMethod", "RegisterStep().WithExecutionOrder(1).WithExecutionOrder(2).Handle();"));
        yield return Case<DuplicateStepTriggerAnalyzer>(Compose(typeof(DuplicateStepTriggerAnalyzerTests), "InRegister",
            "RegisterStep().OnCreate().PreOperation().Sync().Handle();\n            RegisterStep().OnCreate().PreOperation().Sync().Handle();"));
        yield return Case<FilesystemAccessAnalyzer>(Harness(typeof(FilesystemAccessAnalyzerTests)) +
            PluginShell.Replace("BODY", "public void Execute(IServiceProvider sp) { var s = System.IO.File.ReadAllText(\"x\"); }"));
        yield return Case<HandlerContextMatchAnalyzer>(Compose(typeof(HandlerContextMatchAnalyzerTests), "InPlugin", "RegisterStep().OnUpdate().PostOperation().Sync().Handle(OnTwo);"));
        yield return Case<HasChangedPreImageAnalyzer>(Compose(typeof(HasChangedPreImageAnalyzerTests), "InClass",
            "public void Reg() { RegisterStep().OnUpdate().PostOperation().Sync().Handle(OnUpd); }\n" +
            "        private void OnUpd(ILocalPluginContext ctx) { ctx.HasChanged(x => x); }"));
        yield return Case<ImageStageAnalyzer>(Compose(typeof(ImageStageAnalyzerTests), "InMethod", "RegisterStep().OnCreate().PostOperation().Sync().WithPreImage(\"name\").Handle();"));
        yield return Case<MissingFilterAnalyzer>(Compose(typeof(MissingFilterAnalyzerTests), "InMethod", "RegisterStep().OnCreate().PostOperation().Disabled().Handle(H);"));
        yield return Case<MutablePluginStateAnalyzer>(Harness(typeof(MutablePluginStateAnalyzerTests)) +
            PluginShell.Replace("BODY", "private int _count; public void Execute(IServiceProvider sp) { }"));
        yield return Case<PartialPluginForTypedImageAnalyzer>(Compose(typeof(PartialPluginForTypedImageAnalyzerTests), "InPlugin", @"
    public sealed class Audit : EntityPluginBase<Account>
    {
        protected override void RegisterPluginSteps()
            => RegisterStep().OnUpdate().PostOperation().Sync().WithPostImage(a => a.Name).Handle(() => { });
    }"));
        yield return Case<PluginExceptionTypeAnalyzer>(Harness(typeof(PluginExceptionTypeAnalyzerTests)) +
            PluginShell.Replace("BODY", "public void Execute(IServiceProvider sp) { throw new InvalidOperationException(\"bad\"); }"));
        yield return Case<RelationshipColumnSelectorAnalyzer>(Compose(typeof(RelationshipColumnSelectorAnalyzerTests), "InMethod", "RegisterStep().FilterOn(a => a.Contacts).Handle();"));
