using System.Text;

namespace Vela.StepApiGen;

/// <summary>Minimal line writer. Always emits LF line endings (the repo's .editorconfig) whatever the host OS.</summary>
internal sealed class CodeWriter
{
    private readonly StringBuilder _sb = new();

    public CodeWriter Line(string text = "")
    {
        _sb.Append(text).Append('\n');
        return this;
    }

    /// <summary>Appends a verbatim multi-line block (each of its lines, LF-terminated).</summary>
    public CodeWriter Block(string text)
    {
        foreach (var line in text.Replace("\r\n", "\n").Split('\n'))
        {
            Line(line);
        }
        return this;
    }

    /// <summary>The <c>&lt;auto-generated&gt;</c> header shared by every generated file. The marker makes Roslyn treat
    /// the file as generated: analyzers that skip generated code skip it, and the nullable context is disabled (no
    /// <c>#nullable</c> directive is emitted, so behaviour matches the pre-generator files).</summary>
    public CodeWriter Header(string description) => Block(
        $"""
        // <auto-generated>
        // {description} Do not edit by hand: generated by tools/codegen/Vela.StepApiGen from MessageModel.cs.
        // Regenerate with `dotnet run --project tools/codegen/Vela.StepApiGen`; CI fails when this file is stale (--check).
        // </auto-generated>
        """);

    public override string ToString() => _sb.ToString();
}
