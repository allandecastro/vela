using System;
using System.Collections.Generic;
using System.Linq;
using System.Text;

namespace Vela.Cli;

/// <summary>A single SDK message request/response field: its name and the resolved C# type string.</summary>
public sealed record SdkMessageField(string Name, string CSharpType);

/// <summary>An SDK message request (<c>sdkmessagerequest</c>) to generate typed Request/Response classes for.
/// <see cref="Name"/> is the request name (what <c>Execute</c> takes, e.g. <c>CloseQuote</c>).</summary>
public sealed record SdkMessage(
    string Name,
    IReadOnlyList<SdkMessageField> RequestFields,
    IReadOnlyList<SdkMessageField> ResponseFields)
{
    private readonly string? _messageName;

    /// <summary>The sdkmessage the request runs on and plugin steps register on (e.g. <c>Close</c> for
    /// <c>CloseQuote</c>). Defaults to <see cref="Name"/>; when it differs the generated request carries
    /// <c>[Vela.Messages.SdkMessage("...")]</c> so <c>On&lt;XxxRequest&gt;()</c> registers on it.</summary>
    public string MessageName
    {
        get => string.IsNullOrWhiteSpace(_messageName) ? Name : _messageName!;
        init => _messageName = value;
    }

    /// <summary>The entity logical names the message applies to (<c>sdkmessagefilter.primaryobjecttypecode</c>).
    /// Drives the generated entity-constrained <c>On&lt;Message&gt;()</c> step extension(s); an empty list (or a
    /// large fan-out) yields a single generic extension instead (see <see cref="SdkMessageGenerator"/>).</summary>
    public IReadOnlyList<string> Entities { get; init; } = Array.Empty<string>();
}

/// <summary>
/// Pure generator for arbitrary SDK message classes: a typed <c>Vela.Messages.TypedRequest</c> (one read-write
/// property per request field, over <c>Parameters</c>) and a typed <c>Vela.Messages.TypedResponse</c> (one
/// read-only property per response field, over <c>Results</c>). Each property is a one-liner over the base
/// <c>Get&lt;T&gt;()</c> / <c>Set(value)</c> helpers. Wrap a base response returned by <c>IOrganizationService</c>
/// with <c>service.Execute(new XxxRequest { ... }).ToResponse&lt;XxxResponse&gt;()</c>.
/// Mirrors <see cref="CustomApiMessageGenerator"/>; the difference is only the metadata source (a message's
/// request/response fields, with CLR types already resolved to C# by <see cref="ClrTypeNameMapper"/>).
/// </summary>
public static class SdkMessageGenerator
{
    /// <param name="messages">The SDK messages to generate typed request/response classes for.</param>
    /// <param name="ns">The target namespace for the generated files.</param>
    /// <param name="entityTypeNames">Optional map from an entity logical name to its early-bound C# type name
    /// (its SchemaName, as the model generator emits it). Used so the entity-constrained <c>On&lt;Message&gt;()</c>
    /// extension references the exact generated type (e.g. <c>new_CustomEntity</c>), not a naive PascalCase of the
    /// logical name (<c>NewCustomentity</c>). When null or missing an entry, falls back to PascalCase.</param>
    /// <param name="generatedEntityLogicalNames">Optional set of the entity logical names actually generated in this
    /// batch. When provided, the per-entity <c>On&lt;Message&gt;()</c> overloads are emitted only for entities in this
    /// set (referencing an absent early-bound type would not compile, CS0246); if none of the message's entities are in
    /// the set, the single unbound generic extension is emitted instead. When null, every entity is assumed present
    /// (the pre-existing behavior).</param>
    public static IReadOnlyList<GeneratedModel> Generate(IEnumerable<SdkMessage> messages, string ns, IReadOnlyDictionary<string, string>? entityTypeNames = null, IReadOnlyCollection<string>? generatedEntityLogicalNames = null)
    {
        if (messages == null)
        {
            throw new ArgumentNullException(nameof(messages));
        }

        if (string.IsNullOrWhiteSpace(ns))
        {
            throw new ArgumentException("A target namespace is required.", nameof(ns));
        }

        HashSet<string>? generatedEntities = generatedEntityLogicalNames == null
            ? null
            : new HashSet<string>(generatedEntityLogicalNames, StringComparer.OrdinalIgnoreCase);

        return messages
            .Where(m => !string.IsNullOrWhiteSpace(m?.Name))
            .OrderBy(m => m.Name, StringComparer.Ordinal)
            .Select(m => new GeneratedModel($"Messages/{m.Name}.cs", GenerateOne(m, ns, entityTypeNames, generatedEntities)))
            .ToList();
    }

    private static string GenerateOne(SdkMessage message, string ns, IReadOnlyDictionary<string, string>? entityTypeNames, HashSet<string>? generatedEntities)
    {
        string request = $"{message.Name}Request";
        string response = $"{message.Name}Response";

        StringBuilder sb = new StringBuilder();
        sb.AppendLine("// <auto-generated/>");
        sb.AppendLine($"namespace {ns}");
        sb.AppendLine("{");
        sb.AppendLine("    using System;");
        sb.AppendLine("    using Microsoft.Xrm.Sdk;");
        sb.AppendLine();

        // Request
        bool divergent = !string.Equals(message.MessageName, message.Name, StringComparison.Ordinal);
        sb.AppendLine(divergent
            ? $"    /// <summary>Typed request for the <c>{message.Name}</c> request (steps register on the <c>{message.MessageName}</c> message).</summary>"
            : $"    /// <summary>Typed request for the <c>{message.Name}</c> message.</summary>");
        if (divergent)
        {
            sb.AppendLine($"    [Vela.Messages.SdkMessage(\"{message.MessageName}\")]");
        }

        sb.AppendLine($"    public partial class {request} : Vela.Messages.TypedRequest");
        sb.AppendLine("    {");
        sb.AppendLine($"        public {request}()");
        sb.AppendLine("        {");
        sb.AppendLine($"            RequestName = \"{message.Name}\";");
        sb.AppendLine("        }");

        foreach (SdkMessageField field in message.RequestFields)
        {
            AppendParameter(sb, field, readOnly: false);
        }

        sb.AppendLine("    }");
        sb.AppendLine();

        // Response
        sb.AppendLine($"    /// <summary>Typed response for the <c>{message.Name}</c> {(divergent ? "request" : "message")}.</summary>");
        sb.AppendLine($"    public partial class {response} : Vela.Messages.TypedResponse");
        sb.AppendLine("    {");

        foreach (SdkMessageField field in message.ResponseFields)
        {
            AppendParameter(sb, field, readOnly: true);
        }

        sb.AppendLine("    }");

        AppendStepExtensions(sb, message, entityTypeNames, generatedEntities);

        sb.AppendLine("}");
        return sb.ToString();
    }

    // The early-bound C# type name for an entity logical name: its generated model type (SchemaName) when known,
    // else a best-effort PascalCase of the logical name (correct for standard entities, whose SchemaName has no
    // underscore).
    private static string EntityTypeName(string logicalName, IReadOnlyDictionary<string, string>? entityTypeNames) =>
        entityTypeNames != null && entityTypeNames.TryGetValue(logicalName, out string? typeName) && !string.IsNullOrEmpty(typeName)
            ? typeName!
            : PascalCase(logicalName);

    // Fan-out ceiling: at or below this many applicable entities we emit one On<Message>() overload per entity;
    // above it (or with no applicable entity, i.e. an all-entity message) we emit a single generic extension.
    private const int EntityFanoutThreshold = 8;

    /// <summary>
    /// Appends the Phase 3b entity-constrained step extension(s) for the message (compile-time entity
    /// applicability). Because <c>On{Name}()</c> extends
    /// <c>Vela.Steps.IStepTrigger&lt;TEntity&gt;</c> for a concrete entity, it is only in scope on a plugin for that
    /// entity, giving compile-time entity-applicability; it delegates to the typed <c>On&lt;{Name}Request&gt;()</c>.
    /// The early-bound entity types are referenced by PascalCase of their logical name and are ASSUMED to be
    /// generated into this same target namespace (the models namespace <c>ns</c>).
    /// </summary>
    private static void AppendStepExtensions(StringBuilder sb, SdkMessage message, IReadOnlyDictionary<string, string>? entityTypeNames, HashSet<string>? generatedEntities)
    {
        // A message name that is not a valid C# identifier cannot form a usable On<Name>() method or class name.
        // Leave the (unchanged) typed Request/Response above as-is and skip the extension rather than emit code
        // that would not compile.
        if (!IsValidIdentifier(message.Name))
        {
            sb.AppendLine();
            sb.AppendLine($"    // No On{message.Name}() step extension: '{message.Name}' is not a valid C# identifier.");
            return;
        }

        string request = $"{message.Name}Request";
        IReadOnlyList<string> entities = message.Entities ?? Array.Empty<string>();

        // Drop any applicable entity not generated in this batch: a per-entity overload referencing an absent
        // early-bound type would not compile (CS0246). When null, every entity is assumed present.
        if (generatedEntities != null)
        {
            entities = entities.Where(generatedEntities.Contains).ToArray();
        }

        bool generic = entities.Count == 0 || entities.Count > EntityFanoutThreshold;

        sb.AppendLine();
        sb.AppendLine($"    /// <summary>Entity-constrained <c>On{message.Name}()</c> step extension(s) for the <c>{message.Name}</c> message (compile-time entity-applicability). The referenced early-bound entity types are assumed to live in this same namespace.</summary>");
        sb.AppendLine($"    public static class {message.Name}StepExtensions");
        sb.AppendLine("    {");

        if (generic)
        {
            // All-entity or large fan-out: a single generic extension over Vela.Steps.IStepTrigger<TEntity> instead of one
            // overload per entity (avoids referencing many early-bound types).
            sb.AppendLine($"        public static Vela.Steps.ITypedStages<TEntity, {request}> On{message.Name}<TEntity>(this Vela.Steps.IStepTrigger<TEntity> builder) where TEntity : Microsoft.Xrm.Sdk.Entity => builder.On<{request}>();");
        }
        else
        {
            bool first = true;
            foreach (string entity in entities)
            {
                if (!first)
                {
                    sb.AppendLine();
                }

                first = false;
                string pascal = EntityTypeName(entity, entityTypeNames);
                sb.AppendLine($"        public static Vela.Steps.ITypedStages<{pascal}, {request}> On{message.Name}(this Vela.Steps.IStepTrigger<{pascal}> builder) => builder.On<{request}>();");
            }
        }

        sb.AppendLine("    }");
    }

    // PascalCase of an entity logical name for referencing its early-bound type: split on '_', capitalise the
    // first letter of each part, keep the rest. Deterministic and simple (e.g. "lead" -> "Lead",
    // "new_customentity" -> "NewCustomentity").
    private static string PascalCase(string logicalName)
    {
        if (string.IsNullOrWhiteSpace(logicalName))
        {
            return logicalName ?? string.Empty;
        }

        return string.Concat(logicalName
            .Split(new[] { '_' }, StringSplitOptions.RemoveEmptyEntries)
            .Select(part => char.ToUpperInvariant(part[0]) + part.Substring(1)));
    }

    private static bool IsValidIdentifier(string name)
    {
        if (string.IsNullOrEmpty(name) || !(char.IsLetter(name[0]) || name[0] == '_'))
        {
            return false;
        }

        foreach (char c in name)
        {
            if (!(char.IsLetterOrDigit(c) || c == '_'))
            {
                return false;
            }
        }

        return true;
    }

    private static void AppendParameter(StringBuilder sb, SdkMessageField field, bool readOnly)
    {
        string type = field.CSharpType;
        (string member, string key) = CSharpIdentifier.Member(field.Name);
        string setArgs = key.Length > 0 ? "value, " + key : "value";
        sb.AppendLine();
        if (readOnly)
        {
            sb.AppendLine($"        public {type} {member} => Get<{type}>({key});");
        }
        else
        {
            sb.AppendLine($"        public {type} {member}");
            sb.AppendLine("        {");
            sb.AppendLine($"            get => Get<{type}>({key});");
            sb.AppendLine($"            set => Set({setArgs});");
            sb.AppendLine("        }");
        }
    }
}
