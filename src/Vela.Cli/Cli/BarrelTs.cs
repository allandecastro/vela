using System;
using System.Collections.Generic;
using System.Text;
using System.Text.RegularExpressions;

namespace Vela.Cli;

/// <summary>
/// Builds the root <c>index.ts</c> barrel for the TypeScript generators: a single module that named-re-exports every
/// symbol the run produced (form-model consts, table interfaces + their <c>defineTable</c> consts, and option-set
/// enums), so a consumer writes <c>import { AccountMain, Contact, ... } from './generated'</c> instead of many deep
/// imports. Named re-exports (never <c>export *</c>) keep esbuild's tree-shaking, and a name is exported once
/// (first occurrence wins) so a table's shared type/value name and any cross-file collision never double-export.
/// </summary>
internal static class BarrelTs
{
    public const string FileName = "index.ts";

    // Scope-neutral: the barrel aggregates whatever the run emitted (forms and/or tables and their option sets).
    public const string Banner = "// Generated by \"vela models --lang ts\" - do not edit by hand.\n";

    // Matches a top-level `export const|interface|enum <Name>` and captures the exported identifier.
    private static readonly Regex ExportPattern = new(
        @"(?m)^export\s+(?:const|interface|enum)\s+([A-Za-z_$][A-Za-z0-9_$]*)",
        RegexOptions.Compiled);

    /// <summary>
    /// Returns the barrel re-exporting every named symbol of <paramref name="files"/> (in file then source order),
    /// or null when there is nothing to export. The barrel file itself is never re-exported.
    /// </summary>
    public static GeneratedModel? Build(IReadOnlyList<GeneratedModel> files)
    {
        HashSet<string> exported = new HashSet<string>(StringComparer.Ordinal);
        StringBuilder sb = new StringBuilder();
        sb.Append(Banner);
        bool any = false;

        foreach (GeneratedModel file in files)
        {
            if (string.Equals(file.FileName, FileName, StringComparison.Ordinal))
            {
                continue;
            }

            List<string> names = new List<string>();
            HashSet<string> local = new HashSet<string>(StringComparer.Ordinal);
            foreach (Match match in ExportPattern.Matches(file.Code))
            {
                string name = match.Groups[1].Value;
                // Dedup within the module (a table's interface and const share a name) and across modules (first wins).
                if (local.Add(name) && exported.Add(name))
                {
                    names.Add(name);
                }
            }

            if (names.Count == 0)
            {
                continue;
            }

            string module = "./" + file.FileName.Substring(0, file.FileName.Length - ".ts".Length);
            sb.Append($"export {{ {string.Join(", ", names)} }} from '{module}';\n");
            any = true;
        }

        return any ? new GeneratedModel(FileName, sb.ToString()) : null;
    }
}
