using System;
using System.Collections.Generic;
using System.Text;
using System.Text.RegularExpressions;

namespace Vela.Cli;

/// <summary>
/// Builds the root <c>index.ts</c> barrel for the TypeScript generators: a single module that named-re-exports every
/// symbol the run produced (form-model consts, table interfaces + their <c>defineTable</c> consts, and option-set
/// enums), so a consumer writes <c>import { AccountMain, Contact, ... } from './generated'</c> instead of many deep
/// imports. Named re-exports (never <c>export *</c>) keep esbuild's tree-shaking, and a name is exported once
/// (first occurrence wins) so a table's shared type/value name and any cross-file collision never double-export.
/// </summary>
internal static class BarrelTs
{
    public const string FileName = "index.ts";

    // Scope-neutral: the barrel aggregates whatever the run emitted (forms and/or tables and their option sets).
    public const string Banner = "// Generated by \"vela models --lang ts\" - do not edit by hand.\n";

    // A top-level named export carrying a runtime VALUE (const/let/var, function, class, enum - with optional
    // declare/async/abstract). A value re-export carries any merged type too.
    private static readonly Regex ValueExport = new(
        @"(?m)^export\s+(?:declare\s+)?(?:const|let|var|async\s+function|function|abstract\s+class|class|enum)\s+([A-Za-z_$][A-Za-z0-9_$]*)",
        RegexOptions.Compiled);

    // A top-level TYPE-only export (interface / type alias). Re-exported with `export type { ... }` so it survives
    // isolated-modules transpilation (esbuild/tsup). Re-exports (`export { ... }`) and default exports are ignored.
    private static readonly Regex TypeExport = new(
        @"(?m)^export\s+(?:declare\s+)?(?:interface|type)\s+([A-Za-z_$][A-Za-z0-9_$]*)",
        RegexOptions.Compiled);

    /// <summary>
    /// Returns the barrel re-exporting every named symbol of <paramref name="files"/> (in file then source order),
    /// or null when there is nothing to export. Value symbols use <c>export { ... }</c>; type-only symbols (an
    /// interface or type alias with no same-name value) use <c>export type { ... }</c>. The barrel itself is skipped.
    /// </summary>
    public static GeneratedModel? Build(IReadOnlyList<GeneratedModel> files)
    {
        HashSet<string> exported = new HashSet<string>(StringComparer.Ordinal);
        StringBuilder sb = new StringBuilder();
        sb.Append(Banner);
        bool any = false;

        foreach (GeneratedModel file in files)
        {
            if (string.Equals(file.FileName, FileName, StringComparison.Ordinal))
            {
                continue;
            }

            List<string> valueNames = OrderedNames(ValueExport, file.Code);
            HashSet<string> valueSet = new HashSet<string>(valueNames, StringComparer.Ordinal);
            // Type-only = declared as interface/type and NOT also a value (a table's interface+const merge to value).
            List<string> typeNames = OrderedNames(TypeExport, file.Code).Where(n => !valueSet.Contains(n)).ToList();

            // Across modules the first occurrence of a name wins; values are considered before type-only names.
            List<string> values = valueNames.Where(n => exported.Add(n)).ToList();
            List<string> types = typeNames.Where(n => exported.Add(n)).ToList();

            if (values.Count == 0 && types.Count == 0)
            {
                continue;
            }

            string module = "./" + file.FileName.Substring(0, file.FileName.Length - ".ts".Length);
            if (values.Count > 0)
            {
                sb.Append($"export {{ {string.Join(", ", values)} }} from '{module}';\n");
            }

            if (types.Count > 0)
            {
                sb.Append($"export type {{ {string.Join(", ", types)} }} from '{module}';\n");
            }

            any = true;
        }

        return any ? new GeneratedModel(FileName, sb.ToString()) : null;
    }

    // Captured identifiers in source order, deduped within the file.
    private static List<string> OrderedNames(Regex pattern, string code)
    {
        List<string> names = new List<string>();
        HashSet<string> seen = new HashSet<string>(StringComparer.Ordinal);
        foreach (Match match in pattern.Matches(code))
        {
            string name = match.Groups[1].Value;
            if (seen.Add(name))
            {
                names.Add(name);
            }
        }

        return names;
    }
}
