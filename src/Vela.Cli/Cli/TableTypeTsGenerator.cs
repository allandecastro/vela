using System;
using System.Collections.Generic;
using System.Linq;
using System.Text;
using Microsoft.Xrm.Sdk.Metadata;

namespace Vela.Cli;

/// <summary>
/// Pure TypeScript table/record generator: the Web API analog of <see cref="ModelGenerator"/> and the twin of
/// <see cref="FormModelTsGenerator"/>. Turns <see cref="EntityMetadata"/> into the record interfaces the vela-client
/// Web API query layer consumes - one <c>tables/&lt;logicalname&gt;.ts</c> per table
/// (<c>export interface &lt;Pascal&gt; extends DataverseRecordMeta</c>) plus the shared <c>option-sets.ts</c>
/// (see <see cref="OptionSetsTs"/>, shared with the <c>--forms</c> path). No Dataverse I/O: feed it metadata (real
/// or <c>FakeEntityMetadata</c>) and it returns the files to write. Deterministic - columns follow metadata order
/// with the primary key first.
/// </summary>
public static class TableTypeTsGenerator
{
    private const string Banner = "// Generated by \"vela models --tables --lang ts\" - do not edit by hand.\n";
    private const string RecordMetaImport = "import type { DataverseRecordMeta } from 'vela-client/webapi';\n";

    // defineTable is a runtime helper (value import), so the interface and the same-named const merge into one
    // type-and-value symbol the query layer consumes.
    private const string DefineTableImport = "import { defineTable } from 'vela-client/webapi';\n";

    // Each table file lives at tables/<logicalname>.ts, so the option-sets/ folder at the output root is one up.
    private const string OptionSetsPrefix = "../";

    // Prettier's default print width: the enum import folds onto one line when it fits, else one enum per line.
    private const int PrintWidth = 80;

    public static IReadOnlyList<GeneratedModel> Generate(IEnumerable<EntityMetadata> entities)
    {
        if (entities == null)
        {
            throw new ArgumentNullException(nameof(entities));
        }

        OptionSetsTs.Registry optionSets = new OptionSetsTs.Registry();

        List<GeneratedModel> files = entities
            .Where(e => !string.IsNullOrWhiteSpace(e?.LogicalName))
            .Select(e => GenerateTable(e, optionSets))
            .ToList();

        // The enums are shared with --forms: a --tables-only run stays self-contained by emitting the same files.
        files.AddRange(OptionSetsTs.GenerateFiles(optionSets));

        // A root index.ts barrel re-exporting every generated symbol, so consumers import from './generated'.
        GeneratedModel? barrel = BarrelTs.Build(files);
        if (barrel != null)
        {
            files.Add(barrel);
        }

        return files;
    }

    private static GeneratedModel GenerateTable(EntityMetadata entity, OptionSetsTs.Registry optionSets)
    {
        string logical = entity.LogicalName.ToLowerInvariant();
        string interfaceName = InterfaceName(entity);
        string primaryId = entity.PrimaryIdAttribute ?? string.Empty;

        // Resolve every storable column (skip companion "<name>name" pseudo-columns, like ModelGenerator) to a
        // record member, in metadata order, dropping the primary key (emitted first, as a required GUID).
        List<Member> members = new List<Member>();
        foreach (AttributeMetadata attribute in entity.Attributes ?? Array.Empty<AttributeMetadata>())
        {
            if (attribute?.LogicalName is not { Length: > 0 } || !attribute.AttributeType.HasValue)
            {
                continue;
            }

            if (!string.IsNullOrEmpty(attribute.AttributeOf) || string.Equals(attribute.LogicalName, primaryId, StringComparison.OrdinalIgnoreCase))
            {
                continue;
            }

            members.AddRange(MapMembers(logical, attribute));
        }

        StringBuilder sb = new StringBuilder();
        sb.Append(Banner);
        sb.Append(RecordMetaImport);
        sb.Append(DefineTableImport);

        // Enum imports in first-reference order, deduped: locals from option-sets/<entity>, globals from
        // option-sets/global. Register each into the shared option-sets files.
        string[] localEnums = members
            .Where(m => m.OptionSet is { IsGlobal: not true } && m.EnumName != null)
            .Select(m => m.EnumName!)
            .Distinct(StringComparer.Ordinal)
            .ToArray();
        string[] globalEnums = members
            .Where(m => m.OptionSet is { IsGlobal: true })
            .Select(m => m.EnumName!)
            .Distinct(StringComparer.Ordinal)
            .ToArray();
        if (localEnums.Length > 0)
        {
            sb.Append(EnumImport(localEnums, OptionSetsTs.EntityModule(OptionSetsPrefix, logical)));
        }

        if (globalEnums.Length > 0)
        {
            sb.Append(EnumImport(globalEnums, OptionSetsTs.GlobalModule(OptionSetsPrefix)));
        }

        foreach (Member member in members.Where(m => m.OptionSet != null))
        {
            optionSets.Register(logical, member.EnumName!, member.OptionSet!);
        }

        sb.Append('\n');
        sb.Append($"export interface {interfaceName} extends DataverseRecordMeta {{\n");
        if (!string.IsNullOrWhiteSpace(primaryId))
        {
            sb.Append($"  {PropertyKey(primaryId)}: string;\n");
        }

        foreach (Member member in members)
        {
            sb.Append(member.Nullable
                ? $"  {PropertyKey(member.Key)}?: {member.Type} | null;\n"
                : $"  {PropertyKey(member.Key)}?: {member.Type};\n");
        }

        sb.Append("}\n");

        // The runtime descriptor: a same-named const (merging with the interface) carrying the entity, primary key
        // and the multi-select columns (the key is omitted when the table has none).
        string[] multiSelect = members
            .Where(m => m.Type.EndsWith("[]", StringComparison.Ordinal))
            .Select(m => m.Key)
            .ToArray();

        sb.Append('\n');
        sb.Append($"export const {interfaceName} = defineTable<{interfaceName}>({{\n");
        sb.Append($"  entity: '{logical}',\n");
        if (!string.IsNullOrWhiteSpace(primaryId))
        {
            sb.Append($"  primaryId: '{primaryId}',\n");
        }

        if (multiSelect.Length > 0)
        {
            sb.Append($"  multiSelect: [{string.Join(", ", multiSelect.Select(c => $"'{c}'"))}],\n");
        }

        sb.Append("});\n");

        return new GeneratedModel($"tables/{logical}.ts", sb.ToString());
    }

    // A record member: its property key, the base TypeScript type (before the ` | null`), the option set it
    // references (so the caller can register the shared enum) if any, and whether the column is nullable (the lookup
    // logical-name annotation is optional but not nullable).
    private sealed record Member(string Key, string Type, string? EnumName, OptionSetMetadata? OptionSet, bool Nullable = true);

    // Maps one attribute to zero or more record members (a multi-target lookup adds its logical-name annotation).
    private static IReadOnlyList<Member> MapMembers(string entity, AttributeMetadata attribute)
    {
        string logical = attribute.LogicalName;

        // Multi-select choice: an array of the shared enum. File/Image columns come back as strings.
        if (attribute is MultiSelectPicklistAttributeMetadata multi && multi.OptionSet?.Options is { Count: > 0 })
        {
            string enumName = OptionSetsTs.EnumName(entity, attribute, multi.OptionSet);
            return new[] { new Member(logical, $"{enumName}[]", enumName, multi.OptionSet) };
        }

        if (attribute is FileAttributeMetadata or ImageAttributeMetadata)
        {
            return new[] { new Member(logical, "string", null, null) };
        }

        switch (attribute.AttributeType)
        {
            case AttributeTypeCode.String:
            case AttributeTypeCode.Memo:
                return new[] { new Member(logical, "string", null, null) };
            case AttributeTypeCode.Integer:
            case AttributeTypeCode.BigInt:
            case AttributeTypeCode.Decimal:
            case AttributeTypeCode.Double:
            case AttributeTypeCode.Money:
                return new[] { new Member(logical, "number", null, null) };
            case AttributeTypeCode.Boolean:
                return new[] { new Member(logical, "boolean", null, null) };
            case AttributeTypeCode.DateTime:
                // The Web API returns date/time columns as ISO 8601 strings, not Date objects.
                return new[] { new Member(logical, "string", null, null) };
            case AttributeTypeCode.Uniqueidentifier:
                return new[] { new Member(logical, "string", null, null) };
            case AttributeTypeCode.Lookup:
            case AttributeTypeCode.Customer:
            case AttributeTypeCode.Owner:
                return LookupMembers(logical, attribute);
            case AttributeTypeCode.Picklist:
            case AttributeTypeCode.State:
            case AttributeTypeCode.Status:
                if (attribute is EnumAttributeMetadata em && em.OptionSet?.Options is { Count: > 0 })
                {
                    string enumName = OptionSetsTs.EnumName(entity, attribute, em.OptionSet);
                    return new[] { new Member(logical, enumName, enumName, em.OptionSet) };
                }

                return new[] { new Member(logical, "number", null, null) };
            case AttributeTypeCode.PartyList:
                // Activity party lists are expanded collections, not a scalar `_value`; omit them from the record.
                return Array.Empty<Member>();
            default:
                return new[] { new Member(logical, "unknown", null, null) };
        }
    }

    // A retrieved record exposes a lookup as its GUID under `_<name>_value`. A multi-target lookup (Customer, Owner,
    // or a polymorphic lookup with more than one target) additionally carries a typed logical-name annotation naming
    // which table the row points at; a single-target lookup does not need it.
    private static IReadOnlyList<Member> LookupMembers(string logical, AttributeMetadata attribute)
    {
        List<Member> members = new List<Member> { new Member($"_{logical}_value", "string", null, null) };

        string[] targets = (attribute as LookupAttributeMetadata)?.Targets ?? Array.Empty<string>();
        if (targets.Length > 1)
        {
            string union = string.Join(" | ", targets.Select(t => $"'{t}'"));
            members.Add(new Member($"_{logical}_value@Microsoft.Dynamics.CRM.lookuplogicalname", union, null, null, Nullable: false));
        }

        return members;
    }

    // Prettier folds the enum import onto one line when it fits the print width, else one enum per line.
    private static string EnumImport(IReadOnlyList<string> enums, string module)
    {
        string single = $"import type {{ {string.Join(", ", enums)} }} from '{module}';";
        if (single.Length <= PrintWidth)
        {
            return single + "\n";
        }

        StringBuilder sb = new StringBuilder();
        sb.Append("import type {\n");
        foreach (string name in enums)
        {
            sb.Append($"  {name},\n");
        }

        sb.Append($"}} from '{module}';\n");
        return sb.ToString();
    }

    // The C# early-bound class name convention, projected onto the record interface: the table's SchemaName, or the
    // logical name with its first letter upper-cased.
    private static string InterfaceName(EntityMetadata entity) =>
        !string.IsNullOrWhiteSpace(entity.SchemaName) ? entity.SchemaName! : Pascalize(entity.LogicalName);

    private static string Pascalize(string value) =>
        string.IsNullOrEmpty(value) ? value : char.ToUpperInvariant(value[0]) + value.Substring(1);

    private static string PropertyKey(string name) => IsIdentifier(name) ? name : TsString(name);

    private static bool IsIdentifier(string name)
    {
        if (string.IsNullOrEmpty(name) || !(char.IsLetter(name[0]) || name[0] == '_' || name[0] == '$'))
        {
            return false;
        }

        return name.All(c => char.IsLetterOrDigit(c) || c == '_' || c == '$');
    }

    // A single-quoted TS string literal for a non-identifier property key (escaping the backslash and the quote).
    private static string TsString(string value) => "'" + value.Replace("\\", "\\\\").Replace("'", "\\'") + "'";
}
