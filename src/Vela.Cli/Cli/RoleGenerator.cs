using System;
using System.Collections.Generic;
using System.Globalization;
using System.Linq;
using System.Text;

namespace Vela.Cli;

/// <summary>A single (table, privilege, access level) grant a security role confers.</summary>
public sealed record RoleGrantModel(string Entity, string Privilege, string AccessLevel);

/// <summary>
/// A security role resolved from Dataverse — its name, the root role id (roles are duplicated per business unit;
/// this is the root/template role id) and its table-privilege grants.
/// </summary>
public sealed record RoleModel(string Name, Guid Id, IReadOnlyList<RoleGrantModel> Grants);

/// <summary>Options for <see cref="RoleGenerator"/>.</summary>
public sealed record RoleGenOptions(string Namespace);

/// <summary>
/// Generates a <c>Roles</c> class from Dataverse security roles, so tests configure the harness with the real role
/// privilege configuration (via <c>WithSecurity(s =&gt; s.Role(Roles.XName, Roles.X))</c>) and the role's GUID. The
/// output goes in the test project and references <c>Vela.Testing.Security</c> (unlike the dependency-light table
/// models). This is a pure metadata-to-code function; the Dataverse query lives in <c>ModelsCommand</c>.
/// </summary>
public static class RoleGenerator
{
    public static GeneratedModel Generate(IEnumerable<RoleModel> roles, RoleGenOptions options)
    {
        if (roles == null)
        {
            throw new ArgumentNullException(nameof(roles));
        }

        if (options == null || string.IsNullOrWhiteSpace(options.Namespace))
        {
            throw new ArgumentException("A target namespace is required.", nameof(options));
        }

        // Deterministic order, and unique C# identifiers even when two role names sanitize to the same base.
        List<RoleModel> ordered = roles
            .Where(r => r != null && !string.IsNullOrWhiteSpace(r.Name))
            .OrderBy(r => r.Name, StringComparer.Ordinal)
            .ToList();

        HashSet<string> usedIdentifiers = new HashSet<string>(StringComparer.Ordinal);

        StringBuilder sb = new StringBuilder();
        sb.AppendLine("// <auto-generated/>");
        sb.AppendLine($"namespace {options.Namespace}");
        sb.AppendLine("{");
        sb.AppendLine("    using System;");
        sb.AppendLine("    using Vela.Testing.Security;");
        sb.AppendLine();
        sb.AppendLine("    /// <summary>");
        sb.AppendLine("    /// Security roles generated from the environment. Configure the harness with a role's real");
        sb.AppendLine("    /// privileges via <c>WithSecurity(s =&gt; s.Role(Roles.XName, Roles.XId, Roles.X).User(userId, buId, Roles.XName))</c>");
        sb.AppendLine("    /// — passing <c>Roles.XId</c> makes systemuserroles/teamroles queries return the real role id, which");
        sb.AppendLine("    /// plugin logic also uses.");
        sb.AppendLine("    /// </summary>");
        sb.AppendLine("    public static class Roles");
        sb.AppendLine("    {");

        for (int i = 0; i < ordered.Count; i++)
        {
            AppendRole(sb, ordered[i], usedIdentifiers, last: i == ordered.Count - 1);
        }

        sb.AppendLine("    }");
        sb.AppendLine("}");

        return new GeneratedModel("Roles.cs", sb.ToString());
    }

    private static void AppendRole(StringBuilder sb, RoleModel role, HashSet<string> usedIdentifiers, bool last)
    {
        string identifier = UniqueIdentifier(role.Name, usedIdentifiers);

        sb.AppendLine($"        /// <summary>The \"{XmlEscape(role.Name)}\" security role.</summary>");
        sb.AppendLine($"        public const string {identifier}Name = \"{Escape(role.Name)}\";");
        sb.AppendLine();
        sb.AppendLine($"        /// <summary>The root id of the \"{XmlEscape(role.Name)}\" security role.</summary>");
        sb.AppendLine($"        public static readonly Guid {identifier}Id = new Guid(\"{role.Id:D}\");");
        sb.AppendLine();
        sb.AppendLine($"        /// <summary>Applies the privileges of the \"{XmlEscape(role.Name)}\" role to a role builder.</summary>");
        sb.AppendLine($"        public static void {identifier}(RoleBuilder r)");
        sb.AppendLine("        {");

        foreach (RoleGrantModel grant in (role.Grants ?? Array.Empty<RoleGrantModel>())
            .Where(g => g != null && !string.IsNullOrWhiteSpace(g.Entity))
            .OrderBy(g => g.Entity, StringComparer.Ordinal)
            .ThenBy(g => g.Privilege, StringComparer.Ordinal))
        {
            sb.AppendLine($"            r.Grant(\"{Escape(grant.Entity)}\", AccessLevel.{grant.AccessLevel}, Privilege.{grant.Privilege});");
        }

        sb.AppendLine("        }");
        if (!last)
        {
            sb.AppendLine();
        }
    }

    // Turns a role name into a unique, valid C# identifier: PascalCase over alphanumeric runs (which always yields
    // an upper-case first letter, so it can't collide with a lower-case C# keyword), prefixed if it would start with
    // a digit, and suffixed (_2, _3, …) when two names sanitize to the same base.
    private static string UniqueIdentifier(string name, HashSet<string> used)
    {
        StringBuilder id = new StringBuilder();
        bool startOfWord = true;
        foreach (char c in name)
        {
            if (char.IsLetterOrDigit(c))
            {
                id.Append(startOfWord ? char.ToUpper(c, CultureInfo.InvariantCulture) : c);
                startOfWord = false;
            }
            else
            {
                startOfWord = true;
            }
        }

        string basic = id.Length == 0 ? "Role" : id.ToString();
        if (char.IsDigit(basic[0]))
        {
            basic = "Role" + basic;
        }

        string candidate = basic;
        int suffix = 2;
        while (!used.Add(candidate))
        {
            candidate = basic + "_" + suffix.ToString(CultureInfo.InvariantCulture);
            suffix++;
        }

        return candidate;
    }

    private static string Escape(string value) => value.Replace("\\", "\\\\").Replace("\"", "\\\"");

    private static string XmlEscape(string value) => value.Replace("&", "&amp;").Replace("<", "&lt;").Replace(">", "&gt;");
}
