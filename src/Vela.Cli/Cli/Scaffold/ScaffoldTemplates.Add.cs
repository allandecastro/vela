{{(requestType is null ? $$"""
            // Arrange: supply the input parameters the Custom API reads, e.g.
            //   .WithInputParameter("AccountId", Guid.NewGuid())
            PluginContextBuilder builder = PluginContext.ForMessage("{{uniqueName}}");
