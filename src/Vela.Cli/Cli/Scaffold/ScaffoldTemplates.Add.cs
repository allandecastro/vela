    /// <summary>The step a generated plugin test drives: its message, the request type of a message without a dedicated service call, the FilterOn properties to set, and its stage (null when unreadable).</summary>
    internal readonly record struct PluginTestStep(string Message, string RequestType, string[] Filters, string? Stage = null);

    /// <summary>
    /// The name each step's tests carry, in the plugin's step order: <c>&lt;Message&gt;_&lt;Stage&gt;</c> (just the
    /// message when the stage is unreadable), suffixed <c>_2</c>, <c>_3</c>... for a repeat of the same message and stage.
    /// The dispatch test is <c>Fires_On_&lt;name&gt;</c>: <c>vela add test</c> recognises the steps a class already tests by it.
    /// </summary>
    internal static string[] PluginTestNames(IReadOnlyList<PluginTestStep> steps)
    {
        Dictionary<string, int> seen = new Dictionary<string, int>(StringComparer.Ordinal);
        string[] names = new string[steps.Count];
        for (int i = 0; i < steps.Count; i++)
        {
            string key = steps[i].Stage is { } stage ? $"{steps[i].Message}_{stage}" : steps[i].Message;
            int count = seen.TryGetValue(key, out int previous) ? previous + 1 : 1;
            seen[key] = count;
            names[i] = count == 1 ? key : $"{key}_{count}";
        }

        return names;
    }

    /// <summary>The dispatch test of the step whose tests are named <paramref name="name"/> (see <see cref="PluginTestNames"/>).</summary>
    internal static string PluginTestFiresMethod(string name) => $"Fires_On_{name}";

    /// <summary>The skipped behaviour skeleton of the step whose tests are named <paramref name="name"/>.</summary>
    internal static string PluginTestBehaviourMethod(string name) => $"Does_What_It_Should_On_{name}";

    /// <summary>The namespaces the plugin test methods use, which <c>vela add test</c> adds to an existing test file that lacks them.</summary>
    internal static string[] PluginTestUsings(string pluginNamespace, string modelsNamespace) =>
        ["System", "Microsoft.Xrm.Sdk", "Vela.Testing", "Xunit", pluginNamespace, modelsNamespace];

    // The plugin test drives each step through PluginPipeline, which applies the registration as Dataverse does
    // (message, stage, entity, filtering columns, images), and asserts from the ExecutionLog that it fired - whatever the
    // handler does. A second, skipped test per step is the skeleton for asserting that behaviour.
    public static string AddPluginTestFile(string ns, string pluginNamespace, string modelsNamespace, string testClass, string pluginType, string entityType, IReadOnlyList<(PluginTestStep Step, string Name)> tests)
    {
        string usings = string.Concat(PluginTestUsings(pluginNamespace, modelsNamespace).Select(u => $"    using {u};\n"));
        string methods = string.Join("\n", tests.Select(t => PluginTestMethods(pluginType, entityType, t.Step, t.Name)));
        return
$$"""
namespace {{ns}}
{
{{usings.TrimEnd('\n')}}

    /// <summary>
    /// Tests for <see cref="{{pluginType}}"/>, generated by <c>vela add test</c>. <see cref="PluginPipeline"/> runs the
    /// plugin's registered steps around each request sent through <c>pipeline.Service</c>, as Dataverse does (message,
    /// stage, entity, filtering columns, images), against an in-memory Dataverse - no connection, no mocking library.
    /// </summary>
    public sealed class {{testClass}}
    {
{{methods.TrimEnd('\n')}}
    }
}
""";
    }

    // The two tests of one step (the dispatch test alone when behaviour is false), as class members indented by 8 spaces, ending with a newline. Each message is driven
    // the way a caller sends it: Create/Update with an entity that sets the step's filtering column(s),
    // Delete/Assign/Retrieve on a seeded record (an EntityReference target), Associate/Disassociate with a
    // relationship, the bulk messages with Targets.
    internal static string PluginTestMethods(string pluginType, string entityType, PluginTestStep step, string name, bool behaviour = true)
    {
        const string I = "            ";
        string logical = $"{entityType}.EntityLogicalNameValue";
        string filters = string.Concat(step.Filters.Select(f => $", {f} = default"));
        string newFiltered = step.Filters.Length > 0 ? $"new {entityType} {{ {filters.Substring(2)} }}" : $"new {entityType}()";
        string filterNote = step.Filters.Length > 0
            ? $"{I}// The step filters on {string.Join(", ", step.Filters)}, so the request sets {(step.Filters.Length > 1 ? "them (TODO: give them real values)" : "it (TODO: give it a real value)")}.\n"
            : $"{I}// TODO: set the column(s) the step filters on (FilterOn): a Create/Update step fires only when the request sets one.\n";
        string seed = $"{I}Guid id = Guid.NewGuid();\n{I}pipeline.Seed(new {entityType} {{ Id = id }});\n";
        string relationship =
            $"{I}// TODO: your relationship. WithManyToMany declares it (schema name, intersect table, both sides) to the in-memory store.\n" +
            $"{I}const string RelationshipName = \"todo_relationship\";\n" +
            $"{I}pipeline.WithManyToMany(RelationshipName, \"todo_intersect\", {logical}, \"todo_firstid\", {logical}, \"todo_secondid\");\n" +
            $"{I}Guid id = Guid.NewGuid();\n{I}Guid relatedId = Guid.NewGuid();\n" +
            $"{I}pipeline.Seed(new {entityType} {{ Id = id }}, new {entityType} {{ Id = relatedId }});\n" +
            $"{I}EntityReferenceCollection related = new EntityReferenceCollection {{ new EntityReference({logical}, relatedId) }};\n";

        bool typed = true;
        string act = step.Message switch
        {
            "Create" => filterNote + $"{I}pipeline.Service.Create({newFiltered});\n",
            "Update" => seed + filterNote + $"{I}pipeline.Service.Update(new {entityType} {{ Id = id{filters} }});\n",
            "CreateMultiple" => filterNote +
                $"{I}pipeline.Service.Execute(new Microsoft.Xrm.Sdk.Messages.CreateMultipleRequest\n{I}{{\n" +
                $"{I}    Targets = new EntityCollection(new Entity[] {{ {newFiltered} }}) {{ EntityName = {logical} }},\n{I}}});\n",
            "UpdateMultiple" => seed + filterNote +
                $"{I}pipeline.Service.Execute(new Microsoft.Xrm.Sdk.Messages.UpdateMultipleRequest\n{I}{{\n" +
                $"{I}    Targets = new EntityCollection(new Entity[] {{ new {entityType} {{ Id = id{filters} }} }}) {{ EntityName = {logical} }},\n{I}}});\n",
            "Delete" => seed + $"{I}pipeline.Service.Delete({logical}, id);\n",
            "Retrieve" => seed + $"{I}pipeline.Service.Retrieve({logical}, id, new Microsoft.Xrm.Sdk.Query.ColumnSet(true));\n",
            "RetrieveMultiple" => seed + $"{I}pipeline.Service.RetrieveMultiple(new Microsoft.Xrm.Sdk.Query.QueryExpression({logical}) {{ ColumnSet = new Microsoft.Xrm.Sdk.Query.ColumnSet(true) }});\n",
            "Assign" => seed +
                $"{I}Guid ownerId = Guid.NewGuid();\n{I}pipeline.Seed(new Entity(\"systemuser\", ownerId));\n" +
                $"{I}pipeline.Service.Execute(new Microsoft.Crm.Sdk.Messages.AssignRequest\n{I}{{\n" +
                $"{I}    Target = new EntityReference({logical}, id),\n{I}    Assignee = new EntityReference(\"systemuser\", ownerId),\n{I}}});\n",
            "Associate" => relationship + $"{I}pipeline.Service.Associate({logical}, id, new Relationship(RelationshipName), related);\n",
            // The existing link is seeded straight into the intersect table, so only Disassociate runs through the pipeline.
            "Disassociate" => relationship +
                $"{I}pipeline.Seed(new Entity(\"todo_intersect\", Guid.NewGuid())\n{I}{{\n" +
                $"{I}    [\"todo_firstid\"] = new EntityReference({logical}, id),\n{I}    [\"todo_secondid\"] = new EntityReference({logical}, relatedId),\n{I}}});\n" +
                $"{I}pipeline.Service.Disassociate({logical}, id, new Relationship(RelationshipName), related);\n",
            _ => null!,
        };

        if (act is null)
        {
            // No dedicated service call: send the step's request, whose inputs only the author knows.
            typed = false;
            act = seed +
                $"{I}pipeline.Service.Execute(new {step.RequestType}\n{I}{{\n" +
                $"{I}    // TODO: the inputs {step.Message} needs, e.g. Target = new EntityReference({logical}, id),\n{I}}});\n";
        }

        string label = step.Stage is { } stageName ? $"{step.Message} {stageName}" : step.Message;
        string fires = typed
            ? "[Fact]"
            : $"[Fact(Skip = \"TODO: set the {step.Message} request's inputs above, then remove Skip.\")]";
        // Fully qualified, so an appended test needs no new using.
        string stageCheck = step.Stage is { } stage ? $" && e.Stage == Vela.Constants.PluginStages.{stage}" : string.Empty;
        string assertion = typed
            ? $"e => e.PluginTypeName == typeof({pluginType}).FullName && e.Message == \"{step.Message}\"{stageCheck}"
            : $"e => e.PluginTypeName == typeof({pluginType}).FullName{stageCheck}";
        string firesMethod = PluginTestFiresMethod(name);
        string firesTest =
$$"""
        {{fires}}
        public void {{firesMethod}}()
        {
            // Arrange: Empty().Register<T>() scopes the pipeline to this plugin (FromAssemblyOf<T>() takes them all).
            PluginPipeline pipeline = PluginPipeline.Empty().Register<{{pluginType}}>();

            // Act: send the {{step.Message}} the {{label}} step is registered on.
{{act.TrimEnd('\n')}}

            // Assert: the step fired. What the handler does is the next test's job.
            Assert.Contains(pipeline.ExecutionLog, {{assertion}});
        }

""";
        string behaviourTest =
$$"""
        [Fact(Skip = "TODO: assert what {{pluginType}} does on {{label}}")]
        public void {{PluginTestBehaviourMethod(name)}}()
        {
            // Arrange: seed the rows the plugin reads, e.g. pipeline.Seed(new {{entityType}} { Id = id, ... }).
            PluginPipeline pipeline = PluginPipeline.Empty().Register<{{pluginType}}>();
            Guid id = Guid.NewGuid();
            pipeline.Seed(new {{entityType}} { Id = id });

            // Act: send the {{step.Message}} through pipeline.Service, as in {{firesMethod}}.

            // Assert: read back what the plugin wrote and check it, e.g.
            //   {{entityType}} saved = pipeline.Service.Retrieve({{logical}}, id, new Microsoft.Xrm.Sdk.Query.ColumnSet(true)).ToEntity<{{entityType}}>();
            //   Assert.Equal(expected, saved.SomeColumn);
        }

""";
        return behaviour ? firesTest + "\n" + behaviourTest : firesTest;
    }

    // A typed (bound) Custom API has a generated request type, so its test builds the context from it (message and
    // inputs, no strings); a lightweight (global) one has none and keeps the message name.
