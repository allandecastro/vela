using System;
using System.Collections.Generic;
using System.Globalization;
using System.Linq;
using System.Text;
using Microsoft.Xrm.Sdk;
using Microsoft.Xrm.Sdk.Metadata;

namespace Vela.Cli;

/// <summary>
/// The shared option-sets emitter for the TypeScript generators. Both <see cref="FormModelTsGenerator"/> (the
/// <c>--forms</c> path) and <see cref="TableTypeTsGenerator"/> (the <c>--tables</c> path) reference the same enums,
/// so their naming, ordering and byte layout live here once. Choice columns become numeric TypeScript <c>enum</c>s:
/// a global set (kept once, by its own sanitized name) lands in <c>option-sets/global.ts</c>; a local set (named
/// <c>&lt;entity&gt;_&lt;logicalname&gt;</c>) lands in <c>option-sets/&lt;entity&gt;.ts</c>. A consuming file imports
/// its locals from <c>&lt;prefix&gt;option-sets/&lt;entity&gt;</c> and its globals from
/// <c>&lt;prefix&gt;option-sets/global</c>, where the prefix is depth-adjusted per file. The banner intentionally
/// names <c>--forms</c>: these are shared, canonical artifacts regardless of which command wrote them.
/// </summary>
internal static class OptionSetsTs
{
    public const string GlobalFileName = "option-sets/global.ts";

    // The shared files name --forms so they stay byte-identical no matter which command emitted them.
    public const string Banner = "// Generated by \"vela models --forms --lang ts\" - do not edit by hand.\n";

    public static string EntityFileName(string entity) => $"option-sets/{entity.ToLowerInvariant()}.ts";

    // Module specifiers (extensionless) relative to a consuming file, whose depth gives the prefix ("../" or "../../").
    public static string GlobalModule(string prefix) => $"{prefix}option-sets/global";

    public static string EntityModule(string prefix, string entity) => $"{prefix}option-sets/{entity.ToLowerInvariant()}";

    /// <summary>
    /// Collects option sets in first-reference order, split into globals (shared, deduped by name) and per-entity
    /// locals (deduped by name within an entity), so the emitted files are deterministic.
    /// </summary>
    public sealed class Registry
    {
        private readonly HashSet<string> _globalNames = new HashSet<string>(StringComparer.Ordinal);
        private readonly List<(string Name, OptionSetMetadata Set)> _globals = new List<(string, OptionSetMetadata)>();

        private readonly List<string> _entityOrder = new List<string>();
        private readonly Dictionary<string, List<(string Name, OptionSetMetadata Set)>> _localsByEntity = new Dictionary<string, List<(string, OptionSetMetadata)>>(StringComparer.Ordinal);
        private readonly Dictionary<string, HashSet<string>> _localNames = new Dictionary<string, HashSet<string>>(StringComparer.Ordinal);

        public bool HasAny => _globals.Count > 0 || _entityOrder.Count > 0;

        public IReadOnlyList<(string Name, OptionSetMetadata Set)> Globals => _globals;

        public IReadOnlyList<string> Entities => _entityOrder;

        public IReadOnlyList<(string Name, OptionSetMetadata Set)> LocalsFor(string entity) => _localsByEntity[entity.ToLowerInvariant()];

        public void Register(string entity, string name, OptionSetMetadata set)
        {
            if (set.IsGlobal == true)
            {
                if (_globalNames.Add(name))
                {
                    _globals.Add((name, set));
                }

                return;
            }

            string key = entity.ToLowerInvariant();
            if (!_localsByEntity.TryGetValue(key, out List<(string, OptionSetMetadata)>? list))
            {
                list = new List<(string, OptionSetMetadata)>();
                _localsByEntity[key] = list;
                _localNames[key] = new HashSet<string>(StringComparer.Ordinal);
                _entityOrder.Add(key);
            }

            if (_localNames[key].Add(name))
            {
                list.Add((name, set));
            }
        }
    }

    // Local option sets are named <entity>_<column> (the vela-client fixture convention); a global set keeps its own
    // (sanitized) name so it is shared across the tables that reference it.
    public static string EnumName(string entity, AttributeMetadata attribute, OptionSetMetadata optionSet)
    {
        if (optionSet.IsGlobal == true && !string.IsNullOrWhiteSpace(optionSet.Name))
        {
            return SanitizeIdentifier(optionSet.Name!);
        }

        return SanitizeIdentifier($"{entity}_{attribute.LogicalName}");
    }

    // Emits every option-set file: global.ts first (when any global is referenced), then one <entity>.ts per entity
    // that has locals, in first-reference order.
    public static IEnumerable<GeneratedModel> GenerateFiles(Registry registry)
    {
        if (registry.Globals.Count > 0)
        {
            yield return new GeneratedModel(GlobalFileName, RenderEnums(registry.Globals));
        }

        foreach (string entity in registry.Entities)
        {
            yield return new GeneratedModel(EntityFileName(entity), RenderEnums(registry.LocalsFor(entity)));
        }
    }

    private static string RenderEnums(IReadOnlyList<(string Name, OptionSetMetadata Set)> enums)
    {
        StringBuilder sb = new StringBuilder();
        sb.Append(Banner);
        foreach ((string name, OptionSetMetadata set) in enums)
        {
            sb.Append('\n');
            sb.Append($"export enum {name} {{\n");
            HashSet<string> used = new HashSet<string>(StringComparer.Ordinal);
            foreach (OptionMetadata option in set.Options.OrderBy(o => o.Value ?? 0))
            {
                int value = option.Value ?? 0;
                sb.Append($"  {SanitizeMember(LabelText(option.Label), value, used)} = {value.ToString(CultureInfo.InvariantCulture)},\n");
            }

            sb.Append("}\n");
        }

        return sb.ToString();
    }

    private static string SanitizeIdentifier(string name)
    {
        string filtered = new string(name.Where(c => char.IsLetterOrDigit(c) || c == '_').ToArray());
        if (filtered.Length == 0 || char.IsDigit(filtered[0]))
        {
            filtered = "_" + filtered;
        }

        return filtered;
    }

    private static string SanitizeMember(string? label, int value, HashSet<string> used)
    {
        string filtered = new string((label ?? string.Empty).Where(c => char.IsLetterOrDigit(c) || c == '_').ToArray());
        if (filtered.Length == 0 || !(char.IsLetter(filtered[0]) || filtered[0] == '_'))
        {
            filtered = "_" + (filtered.Length == 0 ? value.ToString(CultureInfo.InvariantCulture) : filtered);
        }

        string candidate = filtered;
        int suffix = value;
        while (!used.Add(candidate))
        {
            candidate = filtered + "_" + suffix++;
        }

        return candidate;
    }

    // Server metadata fills UserLocalizedLabel; client-built labels only fill LocalizedLabels - read either.
    private static string? LabelText(Label? label) =>
        label?.UserLocalizedLabel?.Label ?? label?.LocalizedLabels?.FirstOrDefault()?.Label;
}
