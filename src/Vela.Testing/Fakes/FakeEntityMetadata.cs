using System;
using System.Collections.Generic;
using System.Linq;
using System.Reflection;
using Microsoft.Xrm.Sdk;
using Microsoft.Xrm.Sdk.Client;
using Microsoft.Xrm.Sdk.Metadata;

namespace Vela.Testing
{
    /// <summary>
    /// Builds <see cref="EntityMetadata"/> for the in-memory metadata service without fighting the SDK's
    /// read-only metadata setters. Register the result with <c>WithEntityMetadata(...)</c>, then a plugin's
    /// <c>RetrieveEntityRequest</c>/<c>RetrieveAttributeRequest</c> reads it back. Only the fields tests
    /// usually need are exposed; everything else stays at its SDK default.
    /// </summary>
    public sealed class FakeEntityMetadata
    {
        private readonly EntityMetadata _entity = new EntityMetadata();
        private readonly List<AttributeMetadata> _attributes = new List<AttributeMetadata>();
        private readonly List<ManyToManyRelationshipMetadata> _manyToMany = new List<ManyToManyRelationshipMetadata>();

        // The attribute the facet setters (DisplayName/Required/MaxLength/Targets/…) apply to. Adding an attribute
        // selects it (so chaining a facet right after Attribute(...) configures it); On(...) re-selects an existing
        // one by logical name, which is what makes the From<TEntity>()-derived base composable.
        private AttributeMetadata? _selected;

        private FakeEntityMetadata(string logicalName)
        {
            SetSealed(_entity, nameof(EntityMetadata.LogicalName), logicalName);
            _entity.SchemaName = logicalName;
        }

        /// <summary>Starts a metadata definition for the given table logical name.</summary>
        public static FakeEntityMetadata For(string logicalName) => new FakeEntityMetadata(logicalName);

        /// <summary>
        /// Derives a metadata definition by reflecting over an early-bound type generated by <c>vela models</c>:
        /// each property carrying an <see cref="AttributeLogicalNameAttribute"/> becomes an attribute, its CLR
        /// type maps to an <see cref="AttributeTypeCode"/>, generated option-set enums become picklists, the
        /// conventional <c>{logicalname}id</c> column becomes the primary id, a <c>name</c> column becomes the
        /// primary name, ownership is inferred from the presence of an <c>ownerid</c> column (user-owned with one,
        /// organization-owned without), and max length, numeric
        /// range, required level and lookup targets are recovered from the generated <c>[StringLength]</c> /
        /// <c>[Range]</c> / <c>[RequiredLevel]</c> / <c>[LookupTargets]</c> annotations. This is the zero-connection,
        /// no-hand-written path. It returns the same builder, so chain <c>On(...)</c> + the facet setters to override
        /// anything the early-bound type cannot carry — a non-conventional primary-name column, or multi-select/file/
        /// image/partylist columns (which are skipped here because they have no faithful single mapping).
        /// </summary>
        public static FakeEntityMetadata From<TEntity>() where TEntity : Entity
        {
            Type type = typeof(TEntity);
            string logicalName = type.GetCustomAttribute<EntityLogicalNameAttribute>()?.LogicalName
                ?? type.Name.ToLowerInvariant();
            FakeEntityMetadata meta = new FakeEntityMetadata(logicalName);

            string primaryIdName = logicalName + "id";
            bool ownerSeen = false;

            foreach (PropertyInfo property in type.GetProperties(BindingFlags.Public | BindingFlags.Instance))
            {
                string? logical = property.GetCustomAttribute<AttributeLogicalNameAttribute>()?.LogicalName;
                if (logical == null)
                {
                    continue;
                }

                if (string.Equals(logical, "ownerid", StringComparison.OrdinalIgnoreCase))
                {
                    ownerSeen = true;
                }

                if (string.Equals(logical, primaryIdName, StringComparison.OrdinalIgnoreCase))
                {
                    meta.PrimaryId(logical);
                }
                else
                {
                    Type clr = Nullable.GetUnderlyingType(property.PropertyType) ?? property.PropertyType;

                    if (clr.IsEnum)
                    {
                        meta.Picklist(logical, EnumOptions(clr));
                    }
                    else if (string.Equals(logical, "ownerid", StringComparison.OrdinalIgnoreCase))
                    {
                        // ownerid is an Owner attribute (systemuser/team), not a plain Lookup - map it faithfully so a
                        // test inspecting the metadata sees AttributeTypeCode.Owner.
                        meta.Attribute(logical, AttributeTypeCode.Owner);
                    }
                    else if (string.Equals(logical, "customerid", StringComparison.OrdinalIgnoreCase))
                    {
                        // customerid is a Customer attribute (account/contact), not a plain Lookup.
                        meta.Attribute(logical, AttributeTypeCode.Customer);
                    }
                    else
                    {
                        AttributeTypeCode? typeCode = MapClrType(clr);
                        if (typeCode == null)
                        {
                            // Partylist (EntityCollection), multi-select (IList<enum>), File (byte[]/Guid? —
                            // ambiguous with a plain id), Image, and anything unrecognized have no faithful single
                            // mapping → override-only.
                            continue;
                        }

                        if (typeCode == AttributeTypeCode.String && string.Equals(logical, "name", StringComparison.OrdinalIgnoreCase))
                        {
                            meta.PrimaryName(logical);
                        }
                        else
                        {
                            meta.Attribute(logical, typeCode.Value);
                        }
                    }
                }

                // The generated property carries some facets as annotations ([StringLength] → max length, [Range] →
                // numeric min/max, [RequiredLevel] → required level, [LookupTargets] → lookup targets); recover them
                // onto the attribute we just added (now the selected one).
                ApplyGeneratedFacets(meta, property);
            }

            // A generated class has an ownerid column only for a user/team-owned table, the same inference the store
            // makes from an early-bound row.
            meta.Ownership(ownerSeen ? OwnershipTypes.UserOwned : OwnershipTypes.OrganizationOwned);

            return meta;
        }

        /// <summary>Sets the primary id attribute (and adds it as a Uniqueidentifier column).</summary>
        public FakeEntityMetadata PrimaryId(string attributeLogicalName)
        {
            SetSealed(_entity, nameof(EntityMetadata.PrimaryIdAttribute), attributeLogicalName);
            return Attribute(attributeLogicalName, AttributeTypeCode.Uniqueidentifier);
        }

        /// <summary>Sets the primary name attribute (and adds it as a String column).</summary>
        public FakeEntityMetadata PrimaryName(string attributeLogicalName)
        {
            SetSealed(_entity, nameof(EntityMetadata.PrimaryNameAttribute), attributeLogicalName);
            return Attribute(attributeLogicalName, AttributeTypeCode.String);
        }

        /// <summary>Sets the ownership type (user/team-owned, organization-owned, …).</summary>
        public FakeEntityMetadata Ownership(OwnershipTypes ownership)
        {
            _entity.OwnershipType = ownership;
            return this;
        }

        /// <summary>Overrides the entity schema name (used as the generated class name; defaults to the logical name).</summary>
        public FakeEntityMetadata Schema(string schemaName)
        {
            _entity.SchemaName = schemaName;
            return this;
        }

        /// <summary>Adds an attribute of the given type, optionally with a distinct schema name (PascalCase identifier).</summary>
        public FakeEntityMetadata Attribute(string logicalName, AttributeTypeCode type, string? schemaName = null)
        {
            AttributeMetadata attribute = CreateAttribute(type);
            SetSealed(attribute, nameof(AttributeMetadata.LogicalName), logicalName);
            attribute.SchemaName = schemaName ?? logicalName;
            SetSealed(attribute, nameof(AttributeMetadata.AttributeType), type);
            _attributes.Add(attribute);
            _selected = attribute;
            return this;
        }

        /// <summary>
        /// Re-selects a previously added attribute by logical name so the facet setters below configure it. Makes
        /// the <see cref="From{TEntity}"/>-derived base composable, e.g.
        /// <c>From&lt;Account&gt;().On("name").MaxLength(160).On("primarycontactid").Targets("contact")</c>.
        /// </summary>
        public FakeEntityMetadata On(string attributeLogicalName)
        {
            _selected = _attributes.FirstOrDefault(a => a.LogicalName == attributeLogicalName)
                ?? throw new InvalidOperationException(
                    $"No attribute '{attributeLogicalName}' to configure. Add it first (it is not on the derived or declared metadata).");
            return this;
        }

        /// <summary>Sets the display-name label on the selected attribute.</summary>
        public FakeEntityMetadata DisplayName(string label)
        {
            SetSealed(Current, nameof(AttributeMetadata.DisplayName), new Label(label, 1033));
            return this;
        }

        /// <summary>Sets the description label on the selected attribute.</summary>
        public FakeEntityMetadata Description(string label)
        {
            SetSealed(Current, nameof(AttributeMetadata.Description), new Label(label, 1033));
            return this;
        }

        /// <summary>Sets the required level on the selected attribute.</summary>
        public FakeEntityMetadata Required(AttributeRequiredLevel level)
        {
            SetSealed(Current, nameof(AttributeMetadata.RequiredLevel), new AttributeRequiredLevelManagedProperty(level));
            return this;
        }

        /// <summary>Sets the maximum length on the selected String/Memo attribute.</summary>
        public FakeEntityMetadata MaxLength(int maxLength)
        {
            SetSealed(Current, "MaxLength", maxLength);
            return this;
        }

        /// <summary>Sets the numeric precision on the selected Decimal/Double/Money attribute.</summary>
        public FakeEntityMetadata Precision(int precision)
        {
            SetSealed(Current, "Precision", precision);
            return this;
        }

        /// <summary>Sets the min/max on the selected Integer attribute.</summary>
        public FakeEntityMetadata Range(int min, int max)
        {
            SetSealed(Current, "MinValue", min);
            SetSealed(Current, "MaxValue", max);
            return this;
        }

        /// <summary>Sets the min/max on the selected Decimal/Money attribute.</summary>
        public FakeEntityMetadata Range(decimal min, decimal max)
        {
            SetSealed(Current, "MinValue", min);
            SetSealed(Current, "MaxValue", max);
            return this;
        }

        /// <summary>Sets the lookup target tables on the selected Lookup attribute.</summary>
        public FakeEntityMetadata Targets(params string[] targets)
        {
            SetSealed(Current, "Targets", targets);
            return this;
        }

        private AttributeMetadata Current =>
            _selected ?? throw new InvalidOperationException("Add or select (On) an attribute before configuring it.");

        /// <summary>Adds a Picklist (choice) attribute with the given options.</summary>
        public FakeEntityMetadata Picklist(string logicalName, params (int value, string label)[] options)
        {
            PicklistAttributeMetadata attribute = new PicklistAttributeMetadata { SchemaName = logicalName };
            SetSealed(attribute, nameof(AttributeMetadata.LogicalName), logicalName);
            SetSealed(attribute, nameof(AttributeMetadata.AttributeType), AttributeTypeCode.Picklist);

            OptionSetMetadata optionSet = new OptionSetMetadata();
            foreach ((int value, string label) in options)
            {
                optionSet.Options.Add(new OptionMetadata(new Label(label, 1033), value));
            }

            attribute.OptionSet = optionSet;
            _attributes.Add(attribute);
            _selected = attribute;
            return this;
        }

        /// <summary>
        /// Adds an Image attribute. <paramref name="canStoreFullImage"/> mirrors the column's "Can store full images"
        /// setting: once the table's metadata is registered, downloading a column that does not store full images
        /// (<c>InitializeFileBlocksDownload</c> / <c>DownloadFile</c>) fails with <c>0x80040217</c>, as on the
        /// platform (e.g. <c>account.entityimage</c>).
        /// </summary>
        public FakeEntityMetadata Image(string logicalName, bool canStoreFullImage)
        {
            ImageAttributeMetadata attribute = new ImageAttributeMetadata { SchemaName = logicalName, CanStoreFullImage = canStoreFullImage };
            SetSealed(attribute, nameof(AttributeMetadata.LogicalName), logicalName);
            SetSealed(attribute, nameof(AttributeMetadata.AttributeType), AttributeTypeCode.Virtual);
            _attributes.Add(attribute);
            _selected = attribute;
            return this;
        }

        /// <summary>
        /// Declares a many-to-many relationship carried by this table's metadata. Once registered via
        /// <c>WithEntityMetadata(...)</c>, Associate/Disassociate can resolve the intersect from it, so an
        /// explicit <c>WithManyToMany(...)</c> becomes optional.
        /// </summary>
        public FakeEntityMetadata ManyToMany(string schemaName, string intersectEntity, string entity1, string entity1IntersectAttribute, string entity2, string entity2IntersectAttribute)
        {
            _manyToMany.Add(new ManyToManyRelationshipMetadata
            {
                SchemaName = schemaName,
                IntersectEntityName = intersectEntity,
                Entity1LogicalName = entity1,
                Entity1IntersectAttribute = entity1IntersectAttribute,
                Entity2LogicalName = entity2,
                Entity2IntersectAttribute = entity2IntersectAttribute,
            });
            return this;
        }

        /// <summary>Produces the <see cref="EntityMetadata"/>.</summary>
        public EntityMetadata Build()
        {
            SetSealed(_entity, nameof(EntityMetadata.Attributes), _attributes.ToArray());
            if (_manyToMany.Count > 0)
            {
                SetSealed(_entity, nameof(EntityMetadata.ManyToManyRelationships), _manyToMany.ToArray());
            }

            return _entity;
        }

        // Recovers facets the generated property carries onto the selected attribute: [StringLength] → max length,
        // [Range] → numeric min/max (both System.ComponentModel annotations), plus the Vela-generated [RequiredLevel]
        // → required level and [LookupTargets] → lookup targets. The DataAnnotations are read by full type name so
        // Vela.Testing needs no DataAnnotations assembly reference; the Vela-generated attributes live in the
        // caller's namespace, so they are matched by simple type name. The [Range] constructor (int vs double) the
        // generator picks is incidental — the selected attribute's own value type is the source of truth, so the
        // range is coerced to it (see SetRangeFromAnnotation).
        private static void ApplyGeneratedFacets(FakeEntityMetadata meta, PropertyInfo property)
        {
            foreach (Attribute annotation in property.GetCustomAttributes())
            {
                Type type = annotation.GetType();

                if (type.FullName == "System.ComponentModel.DataAnnotations.StringLengthAttribute")
                {
                    object? max = type.GetProperty("MaximumLength")?.GetValue(annotation);
                    if (max is int maxLength && maxLength > 0)
                    {
                        meta.MaxLength(maxLength);
                    }
                }
                else if (type.FullName == "System.ComponentModel.DataAnnotations.RangeAttribute")
                {
                    object? min = type.GetProperty("Minimum")?.GetValue(annotation);
                    object? max = type.GetProperty("Maximum")?.GetValue(annotation);
                    if (min != null && max != null)
                    {
                        meta.SetRangeFromAnnotation(Convert.ToDouble(min), Convert.ToDouble(max));
                    }
                }
                else if (type.Name == "RequiredLevelAttribute")
                {
                    if (type.GetProperty("Level")?.GetValue(annotation) is AttributeRequiredLevel level)
                    {
                        meta.Required(level);
                    }
                }
                else if (type.Name == "LookupTargetsAttribute")
                {
                    // Only meaningful on a lookup; From<T>() maps every EntityReference column to a Lookup, so the
                    // selected attribute is a LookupAttributeMetadata for the columns that carry this annotation.
                    if (type.GetProperty("Targets")?.GetValue(annotation) is string[] targets
                        && targets.Length > 0
                        && meta.Current is LookupAttributeMetadata)
                    {
                        meta.Targets(targets);
                    }
                }
            }
        }

        // [Range(lo, hi)] → the selected numeric attribute's MinValue/MaxValue, coerced to that attribute's value
        // type (Integer → int, Decimal → decimal, Double/Money → double). Only those four types carry a Range
        // (BigInt and the rest never get [Range] from vela models), so any other selected attribute is a no-op.
        private void SetRangeFromAnnotation(double min, double max)
        {
            switch (Current)
            {
                case IntegerAttributeMetadata _:
                    SetSealed(Current, "MinValue", (int)Math.Round(min));
                    SetSealed(Current, "MaxValue", (int)Math.Round(max));
                    break;
                case DecimalAttributeMetadata _:
                    SetSealed(Current, "MinValue", (decimal)min);
                    SetSealed(Current, "MaxValue", (decimal)max);
                    break;
                case DoubleAttributeMetadata _:
                case MoneyAttributeMetadata _:
                    SetSealed(Current, "MinValue", min);
                    SetSealed(Current, "MaxValue", max);
                    break;
            }
        }

        // Reads an enum's members as picklist options. The generated enum's underlying int values are the
        // Dataverse option values; the member name stands in for the label (early-bound carries no display label).
        private static (int value, string label)[] EnumOptions(Type enumType)
        {
            Array values = Enum.GetValues(enumType);
            (int value, string label)[] options = new (int, string)[values.Length];
            for (int i = 0; i < values.Length; i++)
            {
                object value = values.GetValue(i)!;
                options[i] = (Convert.ToInt32(value), Enum.GetName(enumType, value) ?? value.ToString()!);
            }

            return options;
        }

        // Reverse of the CLI ModelGenerator's type map: a generated property's CLR type → its AttributeTypeCode.
        // Returns null for types with no faithful single mapping (partylist, multi-select, file/image) so the
        // caller skips them rather than emitting a wrong attribute.
        private static AttributeTypeCode? MapClrType(Type clr)
        {
            if (clr == typeof(string)) return AttributeTypeCode.String;
            if (clr == typeof(int)) return AttributeTypeCode.Integer;
            if (clr == typeof(long)) return AttributeTypeCode.BigInt;
            if (clr == typeof(decimal)) return AttributeTypeCode.Decimal;
            if (clr == typeof(double)) return AttributeTypeCode.Double;
            if (clr == typeof(bool)) return AttributeTypeCode.Boolean;
            if (clr == typeof(DateTime)) return AttributeTypeCode.DateTime;
            if (clr == typeof(Guid)) return AttributeTypeCode.Uniqueidentifier;
            if (clr == typeof(Money)) return AttributeTypeCode.Money;
            if (clr == typeof(EntityReference)) return AttributeTypeCode.Lookup;
            if (clr == typeof(OptionSetValue)) return AttributeTypeCode.Picklist;
            return null;
        }

        private static AttributeMetadata CreateAttribute(AttributeTypeCode type)
        {
            switch (type)
            {
                case AttributeTypeCode.Picklist:
                case AttributeTypeCode.State:
                case AttributeTypeCode.Status:
                    return new PicklistAttributeMetadata();
                case AttributeTypeCode.Integer:
                    return new IntegerAttributeMetadata();
                case AttributeTypeCode.BigInt:
                    return new BigIntAttributeMetadata();
                case AttributeTypeCode.Boolean:
                    return new BooleanAttributeMetadata();
                case AttributeTypeCode.DateTime:
                    return new DateTimeAttributeMetadata();
                case AttributeTypeCode.Decimal:
                    return new DecimalAttributeMetadata();
                case AttributeTypeCode.Double:
                    return new DoubleAttributeMetadata();
                case AttributeTypeCode.Money:
                    return new MoneyAttributeMetadata();
                case AttributeTypeCode.Lookup:
                case AttributeTypeCode.Customer:
                case AttributeTypeCode.Owner:
                    return new LookupAttributeMetadata();
                case AttributeTypeCode.Uniqueidentifier:
                    return new UniqueIdentifierAttributeMetadata();
                case AttributeTypeCode.Memo:
                    return new MemoAttributeMetadata();
                default:
                    return new StringAttributeMetadata();
            }
        }

        // Metadata properties like LogicalName/PrimaryIdAttribute/AttributeType/Attributes are read-only on the
        // SDK types (the platform sets them). Set them through the non-public setter for test fixtures.
        private static void SetSealed(object target, string propertyName, object? value)
        {
            PropertyInfo? property = target.GetType().GetProperty(
                propertyName, BindingFlags.Public | BindingFlags.NonPublic | BindingFlags.Instance);
            MethodInfo? setter = property?.GetSetMethod(nonPublic: true);
            if (setter == null)
            {
                throw new InvalidOperationException($"Cannot set metadata property '{propertyName}' on {target.GetType().Name}.");
            }

            setter.Invoke(target, new[] { value });
        }
    }
}
