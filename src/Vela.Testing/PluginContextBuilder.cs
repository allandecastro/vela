        /// <summary>
        /// Sets the message. An SDK request name whose sdkmessage differs is translated to what the platform sends as
        /// <c>MessageName</c> (<c>SendEmail</c> becomes <c>Send</c>, <c>WinQuote</c> becomes <c>Win</c>).
        /// </summary>
        public PluginContextBuilder<TEntity> OnMessage(string messageName)
        {
            Context.MessageName = SdkMessageNames.ToSdkMessage(messageName);
            _messageSet = true;
            return this;
        }

        /// <summary>
        /// Sets the message from a typed request and copies its parameters into <c>InputParameters</c>, so a handler's
        /// <c>ctx.Request</c> reads exactly what the request carries. The message is the sdkmessage the platform runs
        /// the request on (a <c>[SdkMessage]</c> on the request type, else the request name translated like the
        /// step builder does: <c>CloseQuote</c> becomes <c>Close</c>).
        /// </summary>
        /// <param name="request">An SDK request, or one generated by <c>vela models --messages</c> / <c>--custom-apis</c>.</param>
        public PluginContextBuilder<TEntity> WithRequest(OrganizationRequest request)
        {
            if (request == null)
            {
                throw new ArgumentNullException(nameof(request));
            }

            Context.MessageName = SdkMessageNames.ToSdkMessage(request);
            foreach (KeyValuePair<string, object> parameter in request.Parameters)
            {
                Context.InputParameters[parameter.Key] = parameter.Value;
            }

            _messageSet = true;
            return this;
        }

